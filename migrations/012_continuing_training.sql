CREATE TABLE training_settings (
 id INTEGER PRIMARY KEY DEFAULT 1 CHECK(id=1),
 max_file_mib SMALLINT NOT NULL DEFAULT 10 CHECK(max_file_mib BETWEEN 1 AND 10),
 max_total_mib SMALLINT NOT NULL DEFAULT 100 CHECK(max_total_mib BETWEEN 20 AND 500),
 max_resources INTEGER NOT NULL DEFAULT 100 CHECK(max_resources BETWEEN 20 AND 2000),
 updated_by BIGINT REFERENCES accounts(id),
 updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
INSERT INTO training_settings(id) VALUES (1);
CREATE TABLE training_trainer_grants (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 account_id BIGINT NOT NULL REFERENCES accounts(id),
 scope TEXT NOT NULL CHECK(scope IN ('platform','region','school')),
 region_id BIGINT REFERENCES organizations(id),
 organization_id BIGINT REFERENCES organizations(id),
 role_key_at_grant TEXT NOT NULL,
 organization_id_at_grant BIGINT REFERENCES organizations(id),
 granted_by BIGINT NOT NULL REFERENCES accounts(id),
 granted_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 revoked_at TIMESTAMPTZ
);
CREATE UNIQUE INDEX uq_training_trainer_scope ON training_trainer_grants(account_id,scope,coalesce(region_id,0),coalesce(organization_id,0));
CREATE INDEX idx_training_trainer ON training_trainer_grants(account_id,revoked_at);
CREATE TABLE training_courses (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 scope TEXT NOT NULL CHECK(scope IN ('platform','region','school')),
 region_id BIGINT REFERENCES organizations(id),
 organization_id BIGINT REFERENCES organizations(id),
 trainer_id BIGINT NOT NULL REFERENCES accounts(id),
 trainer_grant_id BIGINT REFERENCES training_trainer_grants(id),
 title TEXT NOT NULL,
 description TEXT NOT NULL,
 domain TEXT NOT NULL,
 discipline TEXT,
 target_roles TEXT[] NOT NULL CHECK(cardinality(target_roles) BETWEEN 1 AND 13),
 objectives TEXT NOT NULL,
 program TEXT NOT NULL,
 participation_conditions TEXT NOT NULL DEFAULT '',
 format TEXT NOT NULL CHECK(format IN ('onsite','distance','hybrid','workshop','conference','webinar','seminar','self_paced')),
 duration_minutes INTEGER NOT NULL CHECK(duration_minutes BETWEEN 15 AND 100000),
 provider TEXT NOT NULL,
 mandatory BOOLEAN NOT NULL DEFAULT false,
 min_attendance_percent SMALLINT NOT NULL CHECK(min_attendance_percent BETWEEN 0 AND 100),
 pass_percent SMALLINT NOT NULL CHECK(pass_percent BETWEEN 0 AND 100),
 capacity INTEGER NOT NULL CHECK(capacity BETWEEN 1 AND 1000),
 enrollment_open_at TIMESTAMPTZ,
 enrollment_close_at TIMESTAMPTZ,
 status TEXT NOT NULL DEFAULT 'draft' CHECK(status IN ('draft','published','archived')),
 approved_by BIGINT REFERENCES accounts(id),
 published_at TIMESTAMPTZ,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 CHECK((scope='platform' AND region_id IS NULL AND organization_id IS NULL) OR (scope='region' AND region_id IS NOT NULL AND organization_id IS NULL) OR (scope='school' AND region_id IS NOT NULL AND organization_id IS NOT NULL)),
 CHECK(enrollment_open_at IS NULL OR enrollment_close_at IS NULL OR enrollment_close_at>enrollment_open_at)
);
CREATE INDEX idx_training_scope ON training_courses(scope,region_id,organization_id,status,id DESC);
CREATE TABLE training_sessions (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 course_id BIGINT NOT NULL REFERENCES training_courses(id),
 title TEXT NOT NULL,
 starts_at TIMESTAMPTZ NOT NULL,
 ends_at TIMESTAMPTZ NOT NULL,
 location TEXT NOT NULL DEFAULT '',
 created_by BIGINT NOT NULL REFERENCES accounts(id),
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 CHECK(ends_at>starts_at)
);
CREATE INDEX idx_training_sessions ON training_sessions(course_id,starts_at);
CREATE TABLE training_enrollments (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 course_id BIGINT NOT NULL REFERENCES training_courses(id),
 account_id BIGINT NOT NULL REFERENCES accounts(id),
 status TEXT NOT NULL CHECK(status IN ('invited','confirmed','waitlisted','declined','cancelled','completed')),
 invited_by BIGINT REFERENCES accounts(id),
 enrolled_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 UNIQUE(course_id,account_id)
);
CREATE INDEX idx_training_enrollments_person ON training_enrollments(account_id,id DESC);
CREATE TABLE training_attendance (
 session_id BIGINT NOT NULL REFERENCES training_sessions(id),
 enrollment_id BIGINT NOT NULL REFERENCES training_enrollments(id),
 present BOOLEAN NOT NULL,
 recorded_by BIGINT NOT NULL REFERENCES accounts(id),
 recorded_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 PRIMARY KEY(session_id,enrollment_id)
);
CREATE TABLE training_assessments (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 course_id BIGINT NOT NULL REFERENCES training_courses(id),
 phase TEXT NOT NULL CHECK(phase IN ('pre','post')),
 title TEXT NOT NULL,
 published_at TIMESTAMPTZ,
 created_by BIGINT NOT NULL REFERENCES accounts(id),
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 UNIQUE(course_id,phase)
);
CREATE TABLE training_questions (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 assessment_id BIGINT NOT NULL REFERENCES training_assessments(id),
 kind TEXT NOT NULL CHECK(kind IN ('mcq','short','practical')),
 prompt TEXT NOT NULL,
 choices JSONB,
 answer TEXT,
 points SMALLINT NOT NULL CHECK(points BETWEEN 1 AND 100),
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 CHECK((kind='mcq' AND jsonb_typeof(choices)='array' AND answer IS NOT NULL) OR (kind='short' AND answer IS NOT NULL AND choices IS NULL) OR (kind='practical' AND answer IS NULL AND choices IS NULL))
);
CREATE INDEX idx_training_questions ON training_questions(assessment_id,id);
CREATE TABLE training_attempts (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 assessment_id BIGINT NOT NULL REFERENCES training_assessments(id),
 enrollment_id BIGINT NOT NULL REFERENCES training_enrollments(id),
 responses JSONB NOT NULL,
 auto_points INTEGER NOT NULL DEFAULT 0,
 manual_points INTEGER NOT NULL DEFAULT 0,
 total_points INTEGER NOT NULL,
 score_percent NUMERIC(5,2),
 submitted_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 finalized_at TIMESTAMPTZ,
 UNIQUE(assessment_id,enrollment_id)
);
CREATE TABLE training_manual_grades (
 attempt_id BIGINT NOT NULL REFERENCES training_attempts(id),
 question_id BIGINT NOT NULL REFERENCES training_questions(id),
 points INTEGER NOT NULL CHECK(points>=0),
 feedback TEXT NOT NULL DEFAULT '',
 graded_by BIGINT NOT NULL REFERENCES accounts(id),
 graded_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 PRIMARY KEY(attempt_id,question_id)
);
CREATE TABLE training_certificate_requests (
 enrollment_id BIGINT PRIMARY KEY REFERENCES training_enrollments(id),
 proposed_by BIGINT NOT NULL REFERENCES accounts(id),
 proposed_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 status TEXT NOT NULL DEFAULT 'pending' CHECK(status IN ('pending','approved','rejected')),
 reviewed_by BIGINT REFERENCES accounts(id),
 reviewed_at TIMESTAMPTZ,
 review_note TEXT
);
CREATE TABLE training_certificates (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 enrollment_id BIGINT NOT NULL UNIQUE REFERENCES training_enrollments(id),
 reference TEXT NOT NULL UNIQUE,
 participant_name TEXT NOT NULL,
 course_title TEXT NOT NULL,
 provider TEXT NOT NULL,
 duration_minutes INTEGER NOT NULL,
 validated_by BIGINT NOT NULL REFERENCES accounts(id),
 validator_name TEXT NOT NULL,
 issued_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE training_needs (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 account_id BIGINT NOT NULL REFERENCES accounts(id),
 domain TEXT NOT NULL,
 description TEXT NOT NULL,
 status TEXT NOT NULL DEFAULT 'open' CHECK(status IN ('open','reviewed')),
 reviewed_by BIGINT REFERENCES accounts(id),
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 reviewed_at TIMESTAMPTZ
);
CREATE INDEX idx_training_needs_account ON training_needs(account_id,status);
CREATE TABLE training_resources (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 course_id BIGINT NOT NULL REFERENCES training_courses(id),
 file_name TEXT NOT NULL,
 mime_type TEXT NOT NULL CHECK(mime_type IN ('application/pdf','image/png','image/jpeg','application/vnd.openxmlformats-officedocument.presentationml.presentation','video/mp4','video/webm')),
 file_size INTEGER NOT NULL CHECK(file_size BETWEEN 1 AND 10485760),
 file_data BYTEA NOT NULL,
 sha256 TEXT NOT NULL,
 uploaded_by BIGINT NOT NULL REFERENCES accounts(id),
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 UNIQUE(course_id,uploaded_by,sha256)
);
CREATE INDEX idx_training_resources_course ON training_resources(course_id,id DESC);
CREATE TABLE training_reminders (
 user_id BIGINT NOT NULL REFERENCES accounts(id),
 session_id BIGINT NOT NULL REFERENCES training_sessions(id),
 starts_at TIMESTAMPTZ NOT NULL,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 PRIMARY KEY(user_id,session_id,starts_at)
);
CREATE TABLE training_events (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 course_id BIGINT NOT NULL REFERENCES training_courses(id),
 actor_id BIGINT NOT NULL REFERENCES accounts(id),
 enrollment_id BIGINT REFERENCES training_enrollments(id),
 action TEXT NOT NULL,
 detail JSONB NOT NULL DEFAULT '{}'::jsonb,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_training_events_course ON training_events(course_id,id DESC);
