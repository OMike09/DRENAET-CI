CREATE TRIGGER training_grades_immutable BEFORE UPDATE OR DELETE ON training_manual_grades FOR EACH ROW EXECUTE FUNCTION reject_work_event_mutation();
CREATE TRIGGER training_attendance_immutable BEFORE UPDATE OR DELETE ON training_attendance FOR EACH ROW EXECUTE FUNCTION reject_work_event_mutation();
CREATE TRIGGER training_resources_no_delete BEFORE DELETE ON training_resources FOR EACH ROW EXECUTE FUNCTION reject_work_event_mutation();
