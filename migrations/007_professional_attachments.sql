-- Un seul réglage global, modifiable exclusivement par l'administration générale via l'API.
CREATE TABLE attachment_settings (
 id SMALLINT PRIMARY KEY DEFAULT 1 CHECK (id=1),
 max_file_mib SMALLINT NOT NULL DEFAULT 10 CHECK (max_file_mib BETWEEN 1 AND 10),
 max_total_mib SMALLINT NOT NULL DEFAULT 100 CHECK (max_total_mib BETWEEN 20 AND 250),
 updated_by BIGINT REFERENCES accounts(id),
 updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 CHECK (max_total_mib>=max_file_mib)
);
INSERT INTO attachment_settings(id) VALUES (1);
CREATE TABLE professional_attachments (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 entity_type TEXT NOT NULL CHECK (entity_type IN ('instruction','task','report')),
 entity_id BIGINT NOT NULL CHECK (entity_id>0),
 author_id BIGINT NOT NULL REFERENCES accounts(id),
 region_id BIGINT REFERENCES organizations(id),
 report_round INTEGER,
 file_name TEXT NOT NULL,
 mime_type TEXT NOT NULL CHECK (mime_type IN ('application/pdf','image/png','image/jpeg','audio/webm','audio/ogg','audio/mpeg','audio/mp4','audio/wav')),
 file_size INTEGER NOT NULL CHECK (file_size BETWEEN 1 AND 10485760),
 file_data BYTEA NOT NULL,
 sha256 TEXT NOT NULL,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 CHECK (octet_length(file_data)=file_size),
 CHECK ((entity_type='report' AND report_round BETWEEN 1 AND 50) OR (entity_type<>'report' AND report_round IS NULL)),
 UNIQUE(entity_type,entity_id,author_id,sha256)
);
CREATE INDEX idx_prof_attachments_entity ON professional_attachments(entity_type,entity_id,id);
CREATE INDEX idx_prof_attachments_author ON professional_attachments(author_id,id);
CREATE TRIGGER professional_attachment_no_rewrite BEFORE UPDATE OR DELETE ON professional_attachments FOR EACH ROW EXECUTE FUNCTION reject_work_event_mutation();
