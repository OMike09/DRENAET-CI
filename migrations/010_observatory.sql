-- Colis 10 additif : données déclarées et validées pour l'Observatoire, dans le schéma existant.
CREATE TABLE obs_school_versions (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 school_id BIGINT NOT NULL REFERENCES organizations(id),
 revision INTEGER NOT NULL CHECK (revision BETWEEN 1 AND 100000),
 sector TEXT NOT NULL CHECK (sector IN ('public','private')),
 has_primary BOOLEAN NOT NULL,
 has_secondary BOOLEAN NOT NULL,
 city TEXT NOT NULL,
 commune TEXT NOT NULL,
 locality TEXT NOT NULL DEFAULT '',
 latitude NUMERIC(9,6),
 longitude NUMERIC(9,6),
 administrative_info TEXT NOT NULL DEFAULT '',
 source_kind TEXT NOT NULL CHECK (source_kind IN ('declaration','import')),
 source_reference TEXT,
 status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','validated','rejected')),
 submitted_by BIGINT NOT NULL REFERENCES accounts(id),
 submitted_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 reviewed_by BIGINT REFERENCES accounts(id),
 reviewed_at TIMESTAMPTZ,
 review_note TEXT,
 CHECK (has_primary OR has_secondary),
 CHECK ((latitude IS NULL AND longitude IS NULL) OR (latitude BETWEEN -90 AND 90 AND longitude BETWEEN -180 AND 180)),
 UNIQUE(school_id,revision)
);
CREATE INDEX idx_obs_school_status ON obs_school_versions(school_id,status,revision DESC);
CREATE TABLE obs_staff_versions (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 account_id BIGINT NOT NULL REFERENCES accounts(id),
 school_id BIGINT NOT NULL REFERENCES organizations(id),
 revision INTEGER NOT NULL CHECK (revision BETWEEN 1 AND 100000),
 subjects TEXT[] NOT NULL DEFAULT '{}',
 has_primary BOOLEAN NOT NULL,
 has_secondary BOOLEAN NOT NULL,
 status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','validated','rejected')),
 submitted_by BIGINT NOT NULL REFERENCES accounts(id),
 submitted_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 reviewed_by BIGINT REFERENCES accounts(id),
 reviewed_at TIMESTAMPTZ,
 review_note TEXT,
 CHECK (has_primary OR has_secondary),
 CHECK (cardinality(subjects)<=10),
 UNIQUE(account_id,revision)
);
CREATE INDEX idx_obs_staff_status ON obs_staff_versions(account_id,status,revision DESC);
CREATE TABLE obs_entries (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 entry_type TEXT NOT NULL CHECK (entry_type IN ('progress','difficulty','training','visit','absence','staff_need')),
 school_id BIGINT NOT NULL REFERENCES organizations(id),
 person_id BIGINT REFERENCES accounts(id),
 subject TEXT,
 education_level TEXT CHECK (education_level IN ('primary','secondary')),
 period_start DATE NOT NULL,
 period_end DATE NOT NULL,
 quantity INTEGER CHECK (quantity BETWEEN 1 AND 10000),
 percent SMALLINT CHECK (percent BETWEEN 0 AND 100),
 title TEXT NOT NULL,
 details TEXT NOT NULL DEFAULT '',
 status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','validated','rejected')),
 submitted_by BIGINT NOT NULL REFERENCES accounts(id),
 submitted_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 reviewed_by BIGINT REFERENCES accounts(id),
 reviewed_at TIMESTAMPTZ,
 review_note TEXT,
 CHECK (period_end>=period_start),
 CHECK (entry_type<>'progress' OR (subject IS NOT NULL AND education_level IS NOT NULL AND percent IS NOT NULL)),
 CHECK (entry_type<>'absence' OR person_id IS NOT NULL),
 CHECK (entry_type<>'staff_need' OR quantity IS NOT NULL)
);
CREATE INDEX idx_obs_entries_scope ON obs_entries(school_id,entry_type,status,period_end DESC);
CREATE TABLE obs_report_expectations (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 school_id BIGINT NOT NULL REFERENCES organizations(id),
 region_id BIGINT NOT NULL REFERENCES organizations(id),
 label TEXT NOT NULL,
 period_start DATE NOT NULL,
 period_end DATE NOT NULL,
 due_at TIMESTAMPTZ NOT NULL,
 created_by BIGINT NOT NULL REFERENCES accounts(id),
 report_id BIGINT REFERENCES reports(id),
 linked_by BIGINT REFERENCES accounts(id),
 linked_at TIMESTAMPTZ,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 CHECK (period_end>=period_start),
 UNIQUE(school_id,label,period_start,period_end)
);
CREATE INDEX idx_obs_expectations_region ON obs_report_expectations(region_id,due_at);
CREATE TABLE obs_access_grants (
 account_id BIGINT PRIMARY KEY REFERENCES accounts(id),
 role_key_at_grant TEXT NOT NULL,
 organization_id_at_grant BIGINT NOT NULL REFERENCES organizations(id),
 region_id BIGINT NOT NULL REFERENCES organizations(id),
 school_id BIGINT REFERENCES organizations(id),
 view_staff BOOLEAN NOT NULL DEFAULT false,
 view_pedagogy BOOLEAN NOT NULL DEFAULT true,
 granted_by BIGINT NOT NULL REFERENCES accounts(id),
 updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 CHECK (view_staff OR view_pedagogy)
);
CREATE INDEX idx_obs_grants_region ON obs_access_grants(region_id,school_id);
CREATE TABLE obs_rules (
 region_id BIGINT PRIMARY KEY REFERENCES organizations(id),
 stale_days SMALLINT NOT NULL DEFAULT 90 CHECK (stale_days BETWEEN 7 AND 365),
 grace_days SMALLINT NOT NULL DEFAULT 0 CHECK (grace_days BETWEEN 0 AND 30),
 updated_by BIGINT REFERENCES accounts(id),
 updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
-- Les validations ne changent jamais le contenu déclaré. Une correction crée une nouvelle version.
CREATE OR REPLACE FUNCTION obs_review_guard() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF to_jsonb(NEW) - 'status' - 'reviewed_by' - 'reviewed_at' - 'review_note' <> to_jsonb(OLD) - 'status' - 'reviewed_by' - 'reviewed_at' - 'review_note'
    OR OLD.status<>'pending' OR NEW.status NOT IN ('validated','rejected') OR NEW.reviewed_by IS NULL OR NEW.reviewed_at IS NULL THEN
  RAISE EXCEPTION 'Une déclaration validée ne peut être réécrite';
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER obs_school_review_guard BEFORE UPDATE ON obs_school_versions FOR EACH ROW EXECUTE FUNCTION obs_review_guard();
CREATE TRIGGER obs_staff_review_guard BEFORE UPDATE ON obs_staff_versions FOR EACH ROW EXECUTE FUNCTION obs_review_guard();
CREATE TRIGGER obs_entry_review_guard BEFORE UPDATE ON obs_entries FOR EACH ROW EXECUTE FUNCTION obs_review_guard();
CREATE TRIGGER obs_school_no_delete BEFORE DELETE ON obs_school_versions FOR EACH ROW EXECUTE FUNCTION reject_work_event_mutation();
CREATE TRIGGER obs_staff_no_delete BEFORE DELETE ON obs_staff_versions FOR EACH ROW EXECUTE FUNCTION reject_work_event_mutation();
CREATE TRIGGER obs_entry_no_delete BEFORE DELETE ON obs_entries FOR EACH ROW EXECUTE FUNCTION reject_work_event_mutation();
CREATE OR REPLACE FUNCTION obs_expectation_guard() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF OLD.report_id IS NOT NULL OR NEW.report_id IS NULL OR NEW.linked_by IS NULL OR NEW.linked_at IS NULL
 OR to_jsonb(NEW) - 'report_id' - 'linked_by' - 'linked_at' <> to_jsonb(OLD) - 'report_id' - 'linked_by' - 'linked_at' THEN
  RAISE EXCEPTION 'Une échéance ne peut être réécrite';
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER obs_expectation_guard BEFORE UPDATE ON obs_report_expectations FOR EACH ROW EXECUTE FUNCTION obs_expectation_guard();
CREATE TRIGGER obs_expectation_no_delete BEFORE DELETE ON obs_report_expectations FOR EACH ROW EXECUTE FUNCTION reject_work_event_mutation();
