-- Étape 5 additive : alertes internes pour les modules des étapes 3 et 4.
-- Aucun abonnement ou push système n'est simulé ici.
CREATE TABLE activity_notifications (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id BIGINT NOT NULL REFERENCES accounts(id),
 kind TEXT NOT NULL,
 entity_type TEXT NOT NULL CHECK(entity_type IN ('message','report','library','calendar')),
 entity_id BIGINT NOT NULL,
 event_id BIGINT,
 event_key TEXT NOT NULL,
 title TEXT NOT NULL,
 read_at TIMESTAMPTZ,
 opened_at TIMESTAMPTZ,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 UNIQUE(user_id,event_key)
);
CREATE INDEX idx_activity_notifications_user ON activity_notifications(user_id,id DESC);
CREATE TRIGGER activity_notifications_no_delete BEFORE DELETE ON activity_notifications FOR EACH ROW EXECUTE FUNCTION reject_work_event_mutation();
CREATE OR REPLACE FUNCTION guard_activity_notification_update() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF NEW.user_id<>OLD.user_id OR NEW.kind<>OLD.kind OR NEW.entity_type<>OLD.entity_type OR NEW.entity_id<>OLD.entity_id OR NEW.event_key<>OLD.event_key OR NEW.title<>OLD.title OR NEW.event_id IS DISTINCT FROM OLD.event_id OR NEW.created_at<>OLD.created_at OR (OLD.opened_at IS NOT NULL AND NEW.opened_at IS DISTINCT FROM OLD.opened_at) OR (OLD.read_at IS NOT NULL AND NEW.read_at IS DISTINCT FROM OLD.read_at) THEN
  RAISE EXCEPTION 'Une alerte émise ne peut être réécrite';
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER activity_notifications_guard BEFORE UPDATE ON activity_notifications FOR EACH ROW EXECUTE FUNCTION guard_activity_notification_update();
