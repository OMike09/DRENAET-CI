ALTER TABLE academic_delegations ADD COLUMN can_supervise BOOLEAN NOT NULL DEFAULT false;
CREATE TABLE supervision_rules (
 school_id BIGINT PRIMARY KEY REFERENCES organizations(id),
 max_class_evaluations_per_day SMALLINT NOT NULL DEFAULT 2 CHECK(max_class_evaluations_per_day BETWEEN 1 AND 8),
 updated_by BIGINT NOT NULL REFERENCES accounts(id), updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE exam_programs (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 term_id BIGINT NOT NULL REFERENCES academic_terms(id), school_id BIGINT NOT NULL REFERENCES organizations(id),
 class_id BIGINT NOT NULL REFERENCES academic_classes(id), assignment_id BIGINT NOT NULL REFERENCES academic_assignments(id),
 assessment_id BIGINT UNIQUE REFERENCES academic_assessments(id),
 level TEXT NOT NULL, evaluation_type TEXT NOT NULL CHECK(evaluation_type IN ('written_quiz','supervised','level_exam','composition','practical','oral','other')),
 title TEXT NOT NULL, starts_at TIMESTAMPTZ NOT NULL, ends_at TIMESTAMPTZ NOT NULL, room TEXT NOT NULL,
 observations TEXT NOT NULL DEFAULT '', instructions TEXT NOT NULL DEFAULT '', required_supervisors SMALLINT NOT NULL DEFAULT 1 CHECK(required_supervisors BETWEEN 1 AND 10),
 status TEXT NOT NULL DEFAULT 'draft' CHECK(status IN ('draft','published','cancelled')),
 revision INTEGER NOT NULL DEFAULT 1, exception_reason TEXT,
 created_by BIGINT NOT NULL REFERENCES accounts(id), published_at TIMESTAMPTZ, created_at TIMESTAMPTZ NOT NULL DEFAULT now(), updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 CHECK(ends_at>starts_at)
);
CREATE INDEX idx_exam_programs_time ON exam_programs(school_id,starts_at,ends_at);
CREATE TABLE exam_files (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 program_id BIGINT NOT NULL REFERENCES exam_programs(id), file_name TEXT NOT NULL,
 mime_type TEXT NOT NULL CHECK(mime_type IN ('application/pdf','image/png','image/jpeg')),
 content BYTEA NOT NULL, size_bytes INTEGER NOT NULL CHECK(size_bytes BETWEEN 1 AND 2097152),
 uploaded_by BIGINT NOT NULL REFERENCES accounts(id), created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE exam_actions (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 program_id BIGINT REFERENCES exam_programs(id), assignment_id BIGINT, actor_id BIGINT NOT NULL REFERENCES accounts(id),
 action TEXT NOT NULL, reason TEXT, details JSONB NOT NULL DEFAULT '{}', created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TRIGGER exam_actions_immutable BEFORE UPDATE OR DELETE ON exam_actions FOR EACH ROW EXECUTE FUNCTION reject_work_event_mutation();
CREATE TABLE supervision_unavailability (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 school_id BIGINT NOT NULL REFERENCES organizations(id), teacher_id BIGINT NOT NULL REFERENCES accounts(id),
 starts_at TIMESTAMPTZ NOT NULL, ends_at TIMESTAMPTZ NOT NULL, reason TEXT NOT NULL,
 status TEXT NOT NULL DEFAULT 'pending' CHECK(status IN ('pending','approved','rejected')),
 reviewed_by BIGINT REFERENCES accounts(id), reviewed_at TIMESTAMPTZ, response TEXT,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(), CHECK(ends_at>starts_at)
);
CREATE TABLE supervision_exclusions (
 program_id BIGINT NOT NULL REFERENCES exam_programs(id),teacher_id BIGINT NOT NULL REFERENCES accounts(id),
 reason TEXT NOT NULL,created_by BIGINT NOT NULL REFERENCES accounts(id),created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 PRIMARY KEY(program_id,teacher_id)
);
CREATE TABLE supervision_assignments (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 program_id BIGINT NOT NULL REFERENCES exam_programs(id), teacher_id BIGINT NOT NULL REFERENCES accounts(id),
 status TEXT NOT NULL DEFAULT 'proposed' CHECK(status IN ('proposed','validated','superseded','replaced','cancelled')),
 role TEXT NOT NULL DEFAULT 'Surveillant', revision INTEGER NOT NULL DEFAULT 1,
 replaced_from BIGINT REFERENCES supervision_assignments(id), proposed_by BIGINT NOT NULL REFERENCES accounts(id),
 validated_by BIGINT REFERENCES accounts(id), validated_at TIMESTAMPTZ, cancelled_at TIMESTAMPTZ,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(), updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
ALTER TABLE exam_actions ADD CONSTRAINT exam_actions_assignment_fk FOREIGN KEY(assignment_id) REFERENCES supervision_assignments(id);
CREATE UNIQUE INDEX uq_supervision_active_teacher ON supervision_assignments(program_id,teacher_id) WHERE status IN ('proposed','validated');
CREATE INDEX idx_supervision_teacher ON supervision_assignments(teacher_id,status);
CREATE TABLE supervision_views (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,assignment_id BIGINT NOT NULL REFERENCES supervision_assignments(id),
 revision INTEGER NOT NULL,teacher_id BIGINT NOT NULL REFERENCES accounts(id), viewed_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TRIGGER supervision_views_immutable BEFORE UPDATE OR DELETE ON supervision_views FOR EACH ROW EXECUTE FUNCTION reject_work_event_mutation();
CREATE TABLE supervision_acks (
 assignment_id BIGINT NOT NULL REFERENCES supervision_assignments(id),revision INTEGER NOT NULL,
 teacher_id BIGINT NOT NULL REFERENCES accounts(id),acknowledged_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 PRIMARY KEY(assignment_id,revision)
);
CREATE TRIGGER supervision_acks_immutable BEFORE UPDATE OR DELETE ON supervision_acks FOR EACH ROW EXECUTE FUNCTION reject_work_event_mutation();
