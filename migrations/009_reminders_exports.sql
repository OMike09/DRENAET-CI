-- Colis 9 additif : préférences de rappel et journal de déduplication, sans données anciennes modifiées.
CREATE TABLE reminder_preferences (
 account_id BIGINT PRIMARY KEY REFERENCES accounts(id),
 enabled BOOLEAN NOT NULL DEFAULT true,
 lead_hours SMALLINT NOT NULL DEFAULT 24 CHECK (lead_hours IN (1,6,24,48)),
 updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE reminder_deliveries (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id BIGINT NOT NULL REFERENCES accounts(id),
 entity_type TEXT NOT NULL CHECK (entity_type IN ('instruction','task','calendar')),
 entity_id BIGINT NOT NULL,
 deadline_at TIMESTAMPTZ NOT NULL,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 UNIQUE(user_id,entity_type,entity_id,deadline_at)
);
CREATE INDEX idx_reminder_user ON reminder_deliveries(user_id,id DESC);
CREATE TRIGGER reminder_deliveries_no_rewrite BEFORE UPDATE OR DELETE ON reminder_deliveries FOR EACH ROW EXECUTE FUNCTION reject_work_event_mutation();
ALTER TABLE activity_notifications DROP CONSTRAINT activity_notifications_entity_type_check;
ALTER TABLE activity_notifications ADD CONSTRAINT activity_notifications_entity_type_check CHECK (entity_type IN ('message','report','library','calendar','group','correspondence','reminder_instruction','reminder_task','reminder_calendar'));
