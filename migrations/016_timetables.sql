ALTER TABLE academic_delegations ADD COLUMN can_timetable BOOLEAN NOT NULL DEFAULT false;
CREATE TABLE timetable_settings (
 school_id BIGINT PRIMARY KEY REFERENCES organizations(id),
 morning_start TIME, morning_end TIME, morning_minutes SMALLINT NOT NULL DEFAULT 55 CHECK(morning_minutes BETWEEN 20 AND 180),
 afternoon_start TIME NOT NULL DEFAULT '14:00', afternoon_end TIME,
 afternoon_minutes SMALLINT NOT NULL DEFAULT 55 CHECK(afternoon_minutes BETWEEN 20 AND 180),
 working_days SMALLINT[] NOT NULL DEFAULT ARRAY[1,2,3,4,5]::SMALLINT[],
 joint_breaks BOOLEAN NOT NULL DEFAULT false, break_cosigner_id BIGINT REFERENCES accounts(id),
 revision INTEGER NOT NULL DEFAULT 1, updated_by BIGINT NOT NULL REFERENCES accounts(id),updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 CHECK(morning_start IS NULL OR morning_end IS NULL OR morning_end>morning_start),
 CHECK(afternoon_end IS NULL OR afternoon_end>afternoon_start),
 CHECK(array_length(working_days,1) BETWEEN 1 AND 7)
);
CREATE TABLE timetable_breaks (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,school_id BIGINT NOT NULL REFERENCES organizations(id),
 weekday SMALLINT NOT NULL CHECK(weekday BETWEEN 1 AND 7),kind TEXT NOT NULL CHECK(kind IN ('morning','lunch','afternoon','other')),
 starts_at TIME NOT NULL,ends_at TIME NOT NULL,created_by BIGINT NOT NULL REFERENCES accounts(id),
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),CHECK(ends_at>starts_at)
);
CREATE TABLE timetable_break_proposals (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,school_id BIGINT NOT NULL REFERENCES organizations(id),actor_id BIGINT NOT NULL REFERENCES accounts(id),
 action TEXT NOT NULL CHECK(action IN ('add','remove')),break_id BIGINT REFERENCES timetable_breaks(id),
 weekday SMALLINT,kind TEXT,starts_at TIME,ends_at TIME,reason TEXT NOT NULL,
 chief_signed_by BIGINT REFERENCES accounts(id),ace_signed_by BIGINT REFERENCES accounts(id),status TEXT NOT NULL DEFAULT 'pending' CHECK(status IN ('pending','approved','rejected')),
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),reviewed_at TIMESTAMPTZ
);
CREATE TABLE timetable_class_profiles (
 class_id BIGINT PRIMARY KEY REFERENCES academic_classes(id),school_id BIGINT NOT NULL REFERENCES organizations(id),
 level TEXT NOT NULL,series TEXT NOT NULL DEFAULT '',headcount INTEGER NOT NULL CHECK(headcount BETWEEN 0 AND 500),
 updated_by BIGINT NOT NULL REFERENCES accounts(id),updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE timetable_rooms (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,school_id BIGINT NOT NULL REFERENCES organizations(id),
 name TEXT NOT NULL,capacity INTEGER NOT NULL CHECK(capacity BETWEEN 1 AND 1000),active BOOLEAN NOT NULL DEFAULT true,
 UNIQUE(school_id,name)
);
CREATE TABLE timetable_requirements (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,school_id BIGINT NOT NULL REFERENCES organizations(id),
 class_id BIGINT NOT NULL REFERENCES academic_classes(id),assignment_id BIGINT REFERENCES academic_assignments(id),
 subject TEXT NOT NULL,group_code TEXT NOT NULL DEFAULT '', weekly_minutes INTEGER NOT NULL CHECK(weekly_minutes BETWEEN 20 AND 2400),
 group_size INTEGER CHECK(group_size BETWEEN 1 AND 500),
 session_minutes SMALLINT NOT NULL DEFAULT 55 CHECK(session_minutes BETWEEN 20 AND 180),
 sessions SMALLINT NOT NULL CHECK(sessions BETWEEN 1 AND 20),room_id BIGINT REFERENCES timetable_rooms(id),
 notes TEXT NOT NULL DEFAULT '',created_by BIGINT NOT NULL REFERENCES accounts(id),updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 UNIQUE(class_id,assignment_id,group_code)
);
CREATE TABLE timetable_teacher_windows (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,school_id BIGINT NOT NULL REFERENCES organizations(id),
 teacher_id BIGINT NOT NULL REFERENCES accounts(id),weekday SMALLINT NOT NULL CHECK(weekday BETWEEN 1 AND 7),
 starts_at TIME NOT NULL,ends_at TIME NOT NULL,kind TEXT NOT NULL CHECK(kind IN ('available','unavailable')),
 status TEXT NOT NULL DEFAULT 'pending' CHECK(status IN ('pending','approved','rejected')),
 declared_by BIGINT NOT NULL REFERENCES accounts(id),reviewed_by BIGINT REFERENCES accounts(id),reviewed_at TIMESTAMPTZ,
 reason TEXT NOT NULL, CHECK(ends_at>starts_at)
);
CREATE TABLE timetable_runs (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,school_id BIGINT NOT NULL REFERENCES organizations(id),year_id BIGINT NOT NULL REFERENCES academic_years(id),
 status TEXT NOT NULL DEFAULT 'draft' CHECK(status IN ('draft','published','archived')),
 version INTEGER NOT NULL,revision INTEGER NOT NULL DEFAULT 1,base_run_id BIGINT REFERENCES timetable_runs(id),
 settings_revision INTEGER NOT NULL,input_hash TEXT NOT NULL,effective_from DATE NOT NULL,effective_until DATE NOT NULL,
 generated_by BIGINT NOT NULL REFERENCES accounts(id),published_by BIGINT REFERENCES accounts(id),
 published_at TIMESTAMPTZ,created_at TIMESTAMPTZ NOT NULL DEFAULT now(),updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 UNIQUE(school_id,year_id,version),CHECK(effective_until>=effective_from)
);
CREATE UNIQUE INDEX uq_timetable_published_year ON timetable_runs(year_id) WHERE status='published';
CREATE TABLE timetable_sessions (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,run_id BIGINT NOT NULL REFERENCES timetable_runs(id),
 class_id BIGINT NOT NULL REFERENCES academic_classes(id),assignment_id BIGINT NOT NULL REFERENCES academic_assignments(id),
 requirement_id BIGINT NOT NULL REFERENCES timetable_requirements(id),group_code TEXT NOT NULL DEFAULT '',
 teacher_id BIGINT NOT NULL REFERENCES accounts(id),room_id BIGINT REFERENCES timetable_rooms(id),
 weekday SMALLINT NOT NULL CHECK(weekday BETWEEN 1 AND 7),starts_minute SMALLINT NOT NULL CHECK(starts_minute BETWEEN 0 AND 1439),
 ends_minute SMALLINT NOT NULL CHECK(ends_minute BETWEEN 1 AND 1440),duration_minutes SMALLINT NOT NULL CHECK(duration_minutes BETWEEN 20 AND 180),
 CHECK(ends_minute>starts_minute AND ends_minute-starts_minute=duration_minutes)
);
CREATE INDEX idx_timetable_sessions_teacher ON timetable_sessions(teacher_id,weekday,starts_minute);
CREATE TABLE timetable_actions (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,run_id BIGINT REFERENCES timetable_runs(id),school_id BIGINT NOT NULL REFERENCES organizations(id),
 actor_id BIGINT NOT NULL REFERENCES accounts(id),action TEXT NOT NULL,reason TEXT,
 details JSONB NOT NULL DEFAULT '{}',created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TRIGGER timetable_actions_immutable BEFORE UPDATE OR DELETE ON timetable_actions FOR EACH ROW EXECUTE FUNCTION reject_work_event_mutation();
CREATE TABLE timetable_views (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,run_id BIGINT NOT NULL REFERENCES timetable_runs(id),
 teacher_id BIGINT NOT NULL REFERENCES accounts(id),viewed_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TRIGGER timetable_views_immutable BEFORE UPDATE OR DELETE ON timetable_views FOR EACH ROW EXECUTE FUNCTION reject_work_event_mutation();
CREATE TABLE timetable_acks (
 run_id BIGINT NOT NULL REFERENCES timetable_runs(id),teacher_id BIGINT NOT NULL REFERENCES accounts(id),
 acknowledged_at TIMESTAMPTZ NOT NULL DEFAULT now(),PRIMARY KEY(run_id,teacher_id)
);
CREATE TRIGGER timetable_acks_immutable BEFORE UPDATE OR DELETE ON timetable_acks FOR EACH ROW EXECUTE FUNCTION reject_work_event_mutation();
