CREATE TABLE ui_menu_versions (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 role_key TEXT NOT NULL REFERENCES roles(role_key),revision INTEGER NOT NULL CHECK(revision>0),
 layout JSONB NOT NULL,created_by BIGINT NOT NULL REFERENCES accounts(id),
 action TEXT NOT NULL CHECK(action IN ('save','restore','default')),
 previous_version_id BIGINT REFERENCES ui_menu_versions(id),created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 UNIQUE(role_key,revision)
);
CREATE INDEX ui_menu_versions_lookup ON ui_menu_versions(role_key,revision DESC);
CREATE TRIGGER ui_menu_versions_immutable BEFORE UPDATE OR DELETE ON ui_menu_versions FOR EACH ROW EXECUTE FUNCTION reject_work_event_mutation();
CREATE TABLE ui_media_assets (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 kind TEXT NOT NULL CHECK(kind IN ('avatar','profile_cover','site_cover','logo_main','logo_compact','logo_login','pwa_192','pwa_512')),
 owner_id BIGINT REFERENCES accounts(id),mime_type TEXT NOT NULL CHECK(mime_type IN ('image/png','image/jpeg','image/webp')),
 content BYTEA NOT NULL CHECK(octet_length(content) BETWEEN 32 AND 4194304),
 width INTEGER NOT NULL CHECK(width BETWEEN 32 AND 4096),height INTEGER NOT NULL CHECK(height BETWEEN 32 AND 4096),
 uploaded_by BIGINT NOT NULL REFERENCES accounts(id),created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 CHECK ((kind IN ('avatar','profile_cover') AND owner_id IS NOT NULL) OR (kind NOT IN ('avatar','profile_cover') AND owner_id IS NULL)),
 CHECK (kind NOT IN ('pwa_192','pwa_512') OR mime_type='image/png')
);
CREATE TRIGGER ui_media_assets_immutable BEFORE UPDATE OR DELETE ON ui_media_assets FOR EACH ROW EXECUTE FUNCTION reject_work_event_mutation();
CREATE TABLE ui_profile_media (
 account_id BIGINT PRIMARY KEY REFERENCES accounts(id),
 avatar_asset_id BIGINT REFERENCES ui_media_assets(id),
 legacy_photo_id BIGINT REFERENCES attendance_profile_photos(id),
 cover_asset_id BIGINT REFERENCES ui_media_assets(id),
 changed_by BIGINT REFERENCES accounts(id),updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),revision INTEGER NOT NULL DEFAULT 1,
 CHECK (avatar_asset_id IS NULL OR legacy_photo_id IS NULL)
);
