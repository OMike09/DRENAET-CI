-- Une restauration du défaut correspond à un pointeur NULL ; les versions d'images antérieures restent archivées.
CREATE OR REPLACE FUNCTION guard_ui_media_pointer() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE k TEXT; owner_account BIGINT;
BEGIN
 IF TG_TABLE_NAME='ui_profile_media' THEN
  IF NEW.avatar_asset_id IS NOT NULL THEN SELECT kind,owner_id INTO k,owner_account FROM ui_media_assets WHERE id=NEW.avatar_asset_id; IF k<>'avatar' OR owner_account IS DISTINCT FROM NEW.account_id THEN RAISE EXCEPTION 'Photo hors compte'; END IF; END IF;
  IF NEW.cover_asset_id IS NOT NULL THEN SELECT kind,owner_id INTO k,owner_account FROM ui_media_assets WHERE id=NEW.cover_asset_id; IF k<>'profile_cover' OR owner_account IS DISTINCT FROM NEW.account_id THEN RAISE EXCEPTION 'Couverture hors compte'; END IF; END IF;
 ELSE
  IF NEW.asset_id IS NOT NULL THEN SELECT kind INTO k FROM ui_media_assets WHERE id=NEW.asset_id; IF k IS DISTINCT FROM NEW.kind THEN RAISE EXCEPTION 'Visuel plateforme incompatible'; END IF; END IF;
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER ui_profile_pointer_guard BEFORE INSERT OR UPDATE ON ui_profile_media FOR EACH ROW EXECUTE FUNCTION guard_ui_media_pointer();
CREATE TRIGGER ui_platform_pointer_guard BEFORE INSERT OR UPDATE ON ui_platform_media FOR EACH ROW EXECUTE FUNCTION guard_ui_media_pointer();
