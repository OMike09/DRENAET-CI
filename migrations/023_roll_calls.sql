-- Cahier d'appel additif : les brouillons restent distincts des appels validés.
CREATE TABLE roll_call_scopes (
 school_id BIGINT NOT NULL REFERENCES organizations(id),class_id BIGINT NOT NULL REFERENCES academic_classes(id),
 educator_id BIGINT NOT NULL REFERENCES accounts(id),granted_by BIGINT NOT NULL REFERENCES accounts(id),
 granted_at TIMESTAMPTZ NOT NULL DEFAULT now(),revoked_at TIMESTAMPTZ,
 PRIMARY KEY(class_id,educator_id,granted_at)
);
CREATE UNIQUE INDEX uq_roll_call_scopes_current ON roll_call_scopes(educator_id,class_id) WHERE revoked_at IS NULL;
CREATE TABLE roll_calls (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 term_id BIGINT NOT NULL REFERENCES academic_terms(id),class_id BIGINT NOT NULL REFERENCES academic_classes(id),
 assignment_id BIGINT REFERENCES academic_assignments(id),activity TEXT NOT NULL DEFAULT '',
 called_on DATE NOT NULL,starts_at TIME NOT NULL,ends_at TIME,
 status TEXT NOT NULL DEFAULT 'draft' CHECK(status IN ('draft','validated')),
 revision INTEGER NOT NULL DEFAULT 1,created_by BIGINT NOT NULL REFERENCES accounts(id),
 validated_by BIGINT REFERENCES accounts(id),validated_at TIMESTAMPTZ,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 CHECK(assignment_id IS NOT NULL OR length(btrim(activity))>0),
 CHECK(ends_at IS NULL OR ends_at>starts_at)
);
CREATE INDEX idx_roll_calls_class_date ON roll_calls(class_id,called_on DESC);
CREATE TABLE roll_call_entries (
 call_id BIGINT NOT NULL REFERENCES roll_calls(id),pupil_id BIGINT NOT NULL REFERENCES academic_pupils(id),
 status TEXT NOT NULL CHECK(status IN ('present','absent','late','absent_justified','absent_unjustified')),
 observation TEXT NOT NULL DEFAULT '',updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 PRIMARY KEY(call_id,pupil_id)
);
CREATE TABLE roll_call_events (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,call_id BIGINT NOT NULL REFERENCES roll_calls(id),
 actor_id BIGINT NOT NULL REFERENCES accounts(id),action TEXT NOT NULL,
 reason TEXT,revision INTEGER NOT NULL,snapshot JSONB NOT NULL,created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TRIGGER roll_call_events_immutable BEFORE UPDATE OR DELETE ON roll_call_events FOR EACH ROW EXECUTE FUNCTION reject_work_event_mutation();
CREATE TRIGGER roll_calls_no_delete BEFORE DELETE ON roll_calls FOR EACH ROW EXECUTE FUNCTION reject_work_event_mutation();
