-- Étape 6 : abonnements push volontaires, liés à une session et révocables.
-- Les endpoints/clefs sont des capacités privées : jamais dans les alertes ni dans l'audit.
CREATE TABLE push_subscriptions (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 account_id BIGINT NOT NULL REFERENCES accounts(id),
 session_token_hash TEXT NOT NULL REFERENCES sessions(token_hash) ON DELETE CASCADE,
 endpoint TEXT NOT NULL UNIQUE,
 p256dh TEXT NOT NULL,
 auth_key TEXT NOT NULL,
 consented_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_push_subscriptions_account ON push_subscriptions(account_id);
CREATE TABLE push_deliveries (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 subscription_id BIGINT NOT NULL REFERENCES push_subscriptions(id) ON DELETE CASCADE,
 source TEXT NOT NULL CHECK (source IN ('work','activity')),
 notification_id BIGINT NOT NULL,
 state TEXT NOT NULL DEFAULT 'queued' CHECK (state IN ('queued','leased','sent','failed')),
 attempts SMALLINT NOT NULL DEFAULT 0,
 available_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 lease_until TIMESTAMPTZ,
 last_status INTEGER,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 sent_at TIMESTAMPTZ,
 UNIQUE(subscription_id,source,notification_id)
);
CREATE INDEX idx_push_deliveries_pending ON push_deliveries(available_at,id) WHERE state IN ('queued','leased');
CREATE OR REPLACE FUNCTION enqueue_push_delivery() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 INSERT INTO push_deliveries(subscription_id,source,notification_id)
 SELECT p.id,TG_ARGV[0],NEW.id FROM push_subscriptions p
 JOIN sessions s ON s.token_hash=p.session_token_hash AND s.account_id=p.account_id
 JOIN accounts a ON a.id=p.account_id
 WHERE p.account_id=NEW.user_id AND a.status='active' AND a.auth_version=s.auth_version AND s.expires_at>now()
 ON CONFLICT DO NOTHING;
 RETURN NEW;
END $$;
CREATE TRIGGER push_work_enqueue AFTER INSERT ON work_notifications FOR EACH ROW EXECUTE FUNCTION enqueue_push_delivery('work');
CREATE TRIGGER push_activity_enqueue AFTER INSERT ON activity_notifications FOR EACH ROW EXECUTE FUNCTION enqueue_push_delivery('activity');
