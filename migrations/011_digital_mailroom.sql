-- Colis 11 : enrichissement additif du registre 008. Les courriers anciens restent inchangés.
CREATE TABLE courier_sequences (
 scope_key TEXT NOT NULL,
 year INTEGER NOT NULL CHECK(year BETWEEN 2000 AND 2200),
 direction TEXT NOT NULL CHECK(direction IN ('incoming','outgoing','register_outgoing')),
 last_number INTEGER NOT NULL CHECK(last_number>0),
 PRIMARY KEY(scope_key,year,direction)
);
CREATE TABLE courier_templates (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 scope TEXT NOT NULL CHECK(scope IN ('platform','region','school')),
 region_id BIGINT REFERENCES organizations(id),
 organization_id BIGINT REFERENCES organizations(id),
 owner_id BIGINT NOT NULL REFERENCES accounts(id),
 name TEXT NOT NULL,
 subject TEXT NOT NULL,
 body TEXT NOT NULL,
 active BOOLEAN NOT NULL DEFAULT true,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE courier_flows (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 scope TEXT NOT NULL CHECK(scope IN ('platform','region','school')),
 region_id BIGINT REFERENCES organizations(id),
 organization_id BIGINT REFERENCES organizations(id),
 owner_id BIGINT NOT NULL REFERENCES accounts(id),
 name TEXT NOT NULL,
 direction TEXT NOT NULL CHECK(direction IN ('incoming','outgoing')),
 steps BIGINT[] NOT NULL CHECK(cardinality(steps) BETWEEN 1 AND 8),
 active BOOLEAN NOT NULL DEFAULT true,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE courier_details (
 record_id BIGINT PRIMARY KEY REFERENCES correspondence_records(id),
 registration_number TEXT NOT NULL UNIQUE,
 departure_number TEXT UNIQUE,
 registry_year INTEGER NOT NULL,
 category TEXT NOT NULL,
 service_id BIGINT REFERENCES organizations(id),
 nature TEXT NOT NULL,
 confidentiality TEXT NOT NULL CHECK(confidentiality IN ('normal','internal','confidential','strict')),
 priority TEXT NOT NULL CHECK(priority IN ('normal','high','urgent')),
 received_at TIMESTAMPTZ,
 origin_organization TEXT,
 addressee TEXT NOT NULL,
 body TEXT NOT NULL DEFAULT '',
 due_at TIMESTAMPTZ,
 workflow_id BIGINT REFERENCES courier_flows(id),
 step_index INTEGER NOT NULL DEFAULT 0,
 assignee_id BIGINT REFERENCES accounts(id),
 phase TEXT NOT NULL DEFAULT 'draft' CHECK(phase IN ('draft','awaiting_receipt','in_progress','information_requested','awaiting_validation','validated','signed','transmitted','rejected','returned','closed','archived')),
 approved_by BIGINT REFERENCES accounts(id),
 approved_at TIMESTAMPTZ,
 signed_by BIGINT REFERENCES accounts(id),
 signed_at TIMESTAMPTZ,
 closed_at TIMESTAMPTZ,
 archived_at TIMESTAMPTZ,
 external_email TEXT,
 email_status TEXT CHECK(email_status IN ('queued','sending','sent','failed','awaiting_manual','manual')),
 email_attempts SMALLINT NOT NULL DEFAULT 0,
 email_error TEXT,
 email_sent_at TIMESTAMPTZ,
 linked_type TEXT CHECK(linked_type IN ('instruction','task','report')),
 linked_id BIGINT,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 CHECK((linked_type IS NULL)=(linked_id IS NULL)),
 CHECK((approved_at IS NULL)=(approved_by IS NULL)),
 CHECK((signed_at IS NULL)=(signed_by IS NULL))
);
CREATE INDEX idx_courier_phase ON courier_details(phase,due_at);
CREATE INDEX idx_courier_year ON courier_details(registry_year,category,record_id);
CREATE TABLE courier_access (
 record_id BIGINT NOT NULL REFERENCES correspondence_records(id),
 account_id BIGINT NOT NULL REFERENCES accounts(id),
 granted_by BIGINT NOT NULL REFERENCES accounts(id),
 role_key_at_grant TEXT NOT NULL,
 organization_id_at_grant BIGINT REFERENCES organizations(id),
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 revoked_at TIMESTAMPTZ,
 PRIMARY KEY(record_id,account_id)
);
CREATE INDEX idx_courier_access_person ON courier_access(account_id,record_id);
CREATE TABLE courier_actions (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 record_id BIGINT NOT NULL REFERENCES correspondence_records(id),
 actor_id BIGINT NOT NULL REFERENCES accounts(id),
 target_id BIGINT REFERENCES accounts(id),
 action TEXT NOT NULL,
 note TEXT,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_courier_actions_record ON courier_actions(record_id,id);
CREATE TRIGGER courier_actions_immutable BEFORE UPDATE OR DELETE ON courier_actions FOR EACH ROW EXECUTE FUNCTION reject_work_event_mutation();
CREATE TRIGGER courier_access_no_delete BEFORE DELETE ON courier_access FOR EACH ROW EXECUTE FUNCTION reject_work_event_mutation();

-- Seuls le titre et le résumé d’un nouveau brouillon peuvent être corrigés avant soumission.
CREATE OR REPLACE FUNCTION guard_correspondence_update() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF NEW.id<>OLD.id OR NEW.direction<>OLD.direction OR NEW.scope<>OLD.scope OR NEW.region_id IS DISTINCT FROM OLD.region_id OR NEW.organization_id IS DISTINCT FROM OLD.organization_id OR NEW.created_by<>OLD.created_by OR NEW.external_reference<>OLD.external_reference OR NEW.correspondent<>OLD.correspondent OR ((NEW.subject<>OLD.subject OR NEW.summary<>OLD.summary) AND NOT (OLD.status='registered' AND NEW.status='registered' AND EXISTS(SELECT 1 FROM courier_details WHERE record_id=OLD.id AND phase='draft'))) OR NEW.document_date<>OLD.document_date OR NEW.created_at<>OLD.created_at OR NEW.updated_at<OLD.updated_at OR NOT ((OLD.status='registered' AND NEW.status='registered' AND EXISTS(SELECT 1 FROM courier_details WHERE record_id=OLD.id AND phase='draft')) OR (OLD.status='registered' AND NEW.status IN ('pending','closed')) OR (OLD.status='pending' AND NEW.status='received' AND NEW.current_holder_id=OLD.current_holder_id) OR (OLD.status='received' AND NEW.status IN ('pending','closed'))) THEN
  RAISE EXCEPTION 'Un courrier enregistré ne peut être réécrit';
 END IF;
 RETURN NEW;
END $$;
-- Archivage non destructeur : les dossiers, modèles et circuits ne sont pas supprimables.
CREATE TRIGGER courier_details_no_delete BEFORE DELETE ON courier_details FOR EACH ROW EXECUTE FUNCTION reject_work_event_mutation();
CREATE TRIGGER courier_flows_no_delete BEFORE DELETE ON courier_flows FOR EACH ROW EXECUTE FUNCTION reject_work_event_mutation();
CREATE TRIGGER courier_templates_no_delete BEFORE DELETE ON courier_templates FOR EACH ROW EXECUTE FUNCTION reject_work_event_mutation();
