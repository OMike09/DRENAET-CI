CREATE TABLE parent_links (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,parent_id BIGINT NOT NULL REFERENCES accounts(id),
 pupil_id BIGINT NOT NULL REFERENCES academic_pupils(id),school_id BIGINT NOT NULL REFERENCES organizations(id),
 status TEXT NOT NULL DEFAULT 'proposed' CHECK(status IN ('proposed','approved','revoked')),
 relation TEXT NOT NULL,proof_reference TEXT NOT NULL,
 proposed_by BIGINT NOT NULL REFERENCES accounts(id),approved_by BIGINT REFERENCES accounts(id),approved_at TIMESTAMPTZ,
 revoked_by BIGINT REFERENCES accounts(id),revoked_at TIMESTAMPTZ,revision INTEGER NOT NULL DEFAULT 1,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),UNIQUE(parent_id,pupil_id)
);
CREATE INDEX idx_parent_links_active ON parent_links(parent_id,pupil_id) WHERE status='approved';
CREATE TABLE parent_link_events (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,link_id BIGINT NOT NULL REFERENCES parent_links(id),
 actor_id BIGINT NOT NULL REFERENCES accounts(id),action TEXT NOT NULL,reason TEXT,
 snapshot JSONB NOT NULL,created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TRIGGER parent_link_events_immutable BEFORE UPDATE OR DELETE ON parent_link_events FOR EACH ROW EXECUTE FUNCTION reject_work_event_mutation();
CREATE TABLE parent_publications (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,pupil_id BIGINT NOT NULL REFERENCES academic_pupils(id),
 school_id BIGINT NOT NULL REFERENCES organizations(id),kind TEXT NOT NULL CHECK(kind IN ('lesson','grade','attendance')),
 source_id BIGINT NOT NULL,revision INTEGER NOT NULL,snapshot JSONB NOT NULL,
 published_by BIGINT NOT NULL REFERENCES accounts(id),published_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 revoked_by BIGINT REFERENCES accounts(id),revoked_at TIMESTAMPTZ,
 UNIQUE(pupil_id,kind,source_id,revision)
);
CREATE TRIGGER parent_publications_immutable BEFORE DELETE ON parent_publications FOR EACH ROW EXECUTE FUNCTION reject_work_event_mutation();
CREATE TABLE parent_messages (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,link_id BIGINT NOT NULL REFERENCES parent_links(id),
 author_id BIGINT NOT NULL REFERENCES accounts(id),body TEXT NOT NULL,created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TRIGGER parent_messages_immutable BEFORE UPDATE OR DELETE ON parent_messages FOR EACH ROW EXECUTE FUNCTION reject_work_event_mutation();
CREATE TABLE inspector_scopes (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,inspector_id BIGINT NOT NULL REFERENCES accounts(id),
 region_id BIGINT NOT NULL REFERENCES organizations(id),school_id BIGINT REFERENCES organizations(id),
 subject TEXT NOT NULL,granted_by BIGINT NOT NULL REFERENCES accounts(id),created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 revoked_by BIGINT REFERENCES accounts(id),revoked_at TIMESTAMPTZ
);
CREATE INDEX idx_inspector_scopes_current ON inspector_scopes(inspector_id,region_id,subject) WHERE revoked_at IS NULL;
CREATE TABLE governance_dossiers (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,domain TEXT NOT NULL CHECK(domain IN ('coges','exam')),
 category TEXT NOT NULL,title TEXT NOT NULL,body TEXT NOT NULL,school_id BIGINT NOT NULL REFERENCES organizations(id),
 region_id BIGINT NOT NULL REFERENCES organizations(id),year_id BIGINT REFERENCES academic_years(id),
 status TEXT NOT NULL DEFAULT 'draft' CHECK(status IN ('draft','regional_review','national_review','validated','published','returned')),
 revision INTEGER NOT NULL DEFAULT 1,created_by BIGINT NOT NULL REFERENCES accounts(id),
 validated_by BIGINT REFERENCES accounts(id),published_by BIGINT REFERENCES accounts(id),
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_governance_dossiers_scope ON governance_dossiers(region_id,school_id,domain,status);
CREATE TABLE governance_dossier_events (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,dossier_id BIGINT NOT NULL REFERENCES governance_dossiers(id),
 actor_id BIGINT NOT NULL REFERENCES accounts(id),action TEXT NOT NULL,reason TEXT,snapshot JSONB NOT NULL,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TRIGGER governance_dossier_events_immutable BEFORE UPDATE OR DELETE ON governance_dossier_events FOR EACH ROW EXECUTE FUNCTION reject_work_event_mutation();
CREATE TABLE governance_dossier_files (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,dossier_id BIGINT NOT NULL REFERENCES governance_dossiers(id),
 file_name TEXT NOT NULL,mime_type TEXT NOT NULL CHECK(mime_type IN ('application/pdf','image/jpeg','image/png')),
 content BYTEA NOT NULL,size_bytes INTEGER NOT NULL CHECK(size_bytes BETWEEN 1 AND 2097152),
 sha256 TEXT NOT NULL,uploaded_by BIGINT NOT NULL REFERENCES accounts(id),created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 CHECK(octet_length(content)=size_bytes)
);
CREATE TRIGGER governance_dossier_files_immutable BEFORE UPDATE OR DELETE ON governance_dossier_files FOR EACH ROW EXECUTE FUNCTION reject_work_event_mutation();
