CREATE TABLE hierarchy_unit_functions (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,organization_id BIGINT NOT NULL REFERENCES organizations(id),
 template_code TEXT REFERENCES hierarchy_function_templates(code),label TEXT NOT NULL,
 role_key TEXT NOT NULL REFERENCES roles(role_key),active BOOLEAN NOT NULL DEFAULT true,
 created_by BIGINT NOT NULL REFERENCES accounts(id),updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 UNIQUE(organization_id,template_code)
);
CREATE INDEX hierarchy_unit_functions_org ON hierarchy_unit_functions(organization_id,active);
-- Une affectation active par personne : les rôles existants demeurent sources de droits métier.
CREATE TABLE hierarchy_postings (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,account_id BIGINT NOT NULL REFERENCES accounts(id),function_id BIGINT NOT NULL REFERENCES hierarchy_unit_functions(id),
 assigned_by BIGINT NOT NULL REFERENCES accounts(id),started_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 ended_at TIMESTAMPTZ,ended_by BIGINT REFERENCES accounts(id),reason TEXT,
 CHECK(ended_at IS NULL OR ended_at>=started_at)
);
CREATE UNIQUE INDEX hierarchy_postings_current ON hierarchy_postings(account_id) WHERE ended_at IS NULL;
CREATE INDEX hierarchy_postings_function ON hierarchy_postings(function_id) WHERE ended_at IS NULL;
-- Trois liens différents ne confèrent pas les mêmes pouvoirs ; plusieurs missions fonctionnelles possibles.
CREATE TABLE hierarchy_links (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 manager_id BIGINT NOT NULL REFERENCES accounts(id),dependent_id BIGINT NOT NULL REFERENCES accounts(id),
 relation TEXT NOT NULL CHECK(relation IN ('administrative','pedagogical','functional')),
 scope_organization_id BIGINT NOT NULL REFERENCES organizations(id),
 assigned_by BIGINT NOT NULL REFERENCES accounts(id),started_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 ended_at TIMESTAMPTZ,ended_by BIGINT REFERENCES accounts(id),reason TEXT,
 CHECK(manager_id<>dependent_id),CHECK(ended_at IS NULL OR ended_at>=started_at)
);
CREATE UNIQUE INDEX hierarchy_one_admin_superior ON hierarchy_links(dependent_id) WHERE relation='administrative' AND ended_at IS NULL;
CREATE UNIQUE INDEX hierarchy_link_current ON hierarchy_links(manager_id,dependent_id,relation,scope_organization_id) WHERE ended_at IS NULL;
CREATE INDEX hierarchy_links_manager ON hierarchy_links(manager_id,relation) WHERE ended_at IS NULL;
CREATE INDEX hierarchy_links_dependent ON hierarchy_links(dependent_id,relation) WHERE ended_at IS NULL;
-- Circuit explicite : une école peut suivre une inspection / structure, sans changer sa région.
CREATE TABLE hierarchy_school_supervisions (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,school_id BIGINT NOT NULL REFERENCES organizations(id),
 structure_id BIGINT NOT NULL REFERENCES organizations(id),kind TEXT NOT NULL CHECK(kind IN ('administrative','pedagogical')),
 assigned_by BIGINT NOT NULL REFERENCES accounts(id),started_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 ended_at TIMESTAMPTZ,ended_by BIGINT REFERENCES accounts(id),reason TEXT,CHECK(school_id<>structure_id)
);
CREATE UNIQUE INDEX hierarchy_school_supervision_active ON hierarchy_school_supervisions(school_id,structure_id,kind) WHERE ended_at IS NULL;
-- Pouvoirs facultatifs PAR POSTE activé ; aucun rôle générique n'hérite de droits.
CREATE TABLE hierarchy_function_permissions (
 function_id BIGINT NOT NULL REFERENCES hierarchy_unit_functions(id),
 target_role TEXT NOT NULL REFERENCES roles(role_key),action TEXT NOT NULL CHECK(action IN ('view','create','edit','reset','activate','disable','suspend','block','unblock','reactivate','delete','reassign','export','history')),
 enabled BOOLEAN NOT NULL DEFAULT false,updated_by BIGINT NOT NULL REFERENCES accounts(id),updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 PRIMARY KEY(function_id,target_role,action)
);
-- Qualification facultative : les codes existants, l'identité et les données des unités restent intacts.
ALTER TABLE organizations ADD COLUMN hierarchy_kind TEXT;
ALTER TABLE organizations ADD CONSTRAINT organizations_hierarchy_kind_check CHECK (
 hierarchy_kind IS NULL OR
 (kind='service' AND hierarchy_kind IN ('iepp','apfc','cio','cafop','school_life','school_health','literacy','technical_training','other')) OR
 (kind='school' AND hierarchy_kind IN ('preschool','primary','secondary','technical','other'))
);
