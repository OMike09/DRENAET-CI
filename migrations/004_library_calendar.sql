-- Étape 4 additive : bibliothèque privée PostgreSQL et calendrier cloisonné.
CREATE TABLE library_documents (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 created_by BIGINT NOT NULL REFERENCES accounts(id),
 scope TEXT NOT NULL CHECK(scope IN ('private','school','region','platform')),
 region_id BIGINT REFERENCES organizations(id),
 school_id BIGINT REFERENCES organizations(id),
 title TEXT NOT NULL,
 description TEXT NOT NULL DEFAULT '',
 file_name TEXT NOT NULL,
 mime_type TEXT NOT NULL CHECK(mime_type IN ('application/pdf','image/png','image/jpeg')),
 file_size INTEGER NOT NULL CHECK(file_size BETWEEN 1 AND 2097152),
 file_data BYTEA NOT NULL,
 sha256 TEXT NOT NULL,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 archived_at TIMESTAMPTZ,
 archived_by BIGINT REFERENCES accounts(id),
 CHECK (octet_length(file_data)=file_size),
 CHECK ((scope='private' AND region_id IS NULL AND school_id IS NULL)
     OR (scope='school' AND region_id IS NOT NULL AND school_id IS NOT NULL)
     OR (scope='region' AND region_id IS NOT NULL AND school_id IS NULL)
     OR (scope='platform' AND region_id IS NULL AND school_id IS NULL))
);
CREATE INDEX idx_library_documents_scope ON library_documents(scope,region_id,school_id,id DESC);
CREATE INDEX idx_library_documents_creator ON library_documents(created_by,id DESC);
CREATE TRIGGER library_document_no_rewrite BEFORE UPDATE OF created_by,scope,region_id,school_id,title,description,file_name,mime_type,file_size,file_data,sha256,created_at OR DELETE ON library_documents FOR EACH ROW EXECUTE FUNCTION reject_work_event_mutation();

CREATE TABLE calendar_events (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 created_by BIGINT NOT NULL REFERENCES accounts(id),
 scope TEXT NOT NULL CHECK(scope IN ('private','school','region','platform')),
 region_id BIGINT REFERENCES organizations(id),
 school_id BIGINT REFERENCES organizations(id),
 title TEXT NOT NULL,
 description TEXT NOT NULL DEFAULT '',
 location TEXT NOT NULL DEFAULT '',
 starts_at TIMESTAMPTZ NOT NULL,
 ends_at TIMESTAMPTZ NOT NULL,
 status TEXT NOT NULL DEFAULT 'active' CHECK(status IN ('active','cancelled')),
 revision INTEGER NOT NULL DEFAULT 1 CHECK(revision BETWEEN 1 AND 100),
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 CHECK(ends_at>starts_at AND ends_at<=starts_at+interval '30 days'),
 CHECK ((scope='private' AND region_id IS NULL AND school_id IS NULL)
     OR (scope='school' AND region_id IS NOT NULL AND school_id IS NOT NULL)
     OR (scope='region' AND region_id IS NOT NULL AND school_id IS NULL)
     OR (scope='platform' AND region_id IS NULL AND school_id IS NULL))
);
CREATE INDEX idx_calendar_events_region ON calendar_events(scope,region_id,school_id,starts_at);
CREATE INDEX idx_calendar_events_creator ON calendar_events(created_by,starts_at);
CREATE TRIGGER calendar_event_no_delete BEFORE DELETE ON calendar_events FOR EACH ROW EXECUTE FUNCTION reject_work_event_mutation();
CREATE TABLE calendar_event_revisions (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 event_id BIGINT NOT NULL REFERENCES calendar_events(id),
 revision INTEGER NOT NULL,
 actor_id BIGINT NOT NULL REFERENCES accounts(id),
 action TEXT NOT NULL CHECK(action IN ('create','update','cancel')),
 title TEXT NOT NULL,
 description TEXT NOT NULL,
 location TEXT NOT NULL,
 starts_at TIMESTAMPTZ NOT NULL,
 ends_at TIMESTAMPTZ NOT NULL,
 status TEXT NOT NULL,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 UNIQUE(event_id,revision)
);
CREATE INDEX idx_calendar_event_revisions ON calendar_event_revisions(event_id,revision);
CREATE TRIGGER calendar_revisions_no_rewrite BEFORE UPDATE OR DELETE ON calendar_event_revisions FOR EACH ROW EXECUTE FUNCTION reject_work_event_mutation();
