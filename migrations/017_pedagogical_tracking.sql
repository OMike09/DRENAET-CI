CREATE TABLE lesson_program_items (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,term_id BIGINT NOT NULL REFERENCES academic_terms(id),
 assignment_id BIGINT NOT NULL REFERENCES academic_assignments(id),chapter TEXT NOT NULL,lesson_title TEXT NOT NULL,
 ordinal INTEGER NOT NULL CHECK(ordinal BETWEEN 1 AND 10000),created_by BIGINT NOT NULL REFERENCES accounts(id),
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),UNIQUE(term_id,assignment_id,ordinal)
);
CREATE TABLE pedagogical_lessons (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,term_id BIGINT NOT NULL REFERENCES academic_terms(id),
 assignment_id BIGINT NOT NULL REFERENCES academic_assignments(id),program_item_id BIGINT REFERENCES lesson_program_items(id),
 timetable_session_id BIGINT REFERENCES timetable_sessions(id),taught_on DATE NOT NULL,
 starts_at TIME,ends_at TIME,chapter TEXT NOT NULL DEFAULT '',lesson_title TEXT NOT NULL DEFAULT '',title TEXT NOT NULL,
 content JSONB NOT NULL DEFAULT '{}'::jsonb,progress_note TEXT NOT NULL DEFAULT '',
 status TEXT NOT NULL DEFAULT 'draft' CHECK(status IN ('draft','completed','submitted','correction_requested','approved')),
 revision INTEGER NOT NULL DEFAULT 1,created_by BIGINT NOT NULL REFERENCES accounts(id),created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),CHECK(ends_at IS NULL OR starts_at IS NOT NULL AND ends_at>starts_at)
);
CREATE INDEX idx_pedagogical_lessons_term ON pedagogical_lessons(term_id,assignment_id,taught_on DESC);
CREATE TABLE pedagogical_lesson_events (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,lesson_id BIGINT NOT NULL REFERENCES pedagogical_lessons(id),
 actor_id BIGINT NOT NULL REFERENCES accounts(id),action TEXT NOT NULL,reason TEXT,snapshot JSONB NOT NULL,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TRIGGER pedagogical_lesson_events_immutable BEFORE UPDATE OR DELETE ON pedagogical_lesson_events FOR EACH ROW EXECUTE FUNCTION reject_work_event_mutation();
CREATE TABLE pedagogical_lesson_files (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,lesson_id BIGINT NOT NULL REFERENCES pedagogical_lessons(id),
 file_name TEXT NOT NULL,mime_type TEXT NOT NULL CHECK(mime_type IN ('application/pdf','image/png','image/jpeg')),
 content BYTEA NOT NULL,size_bytes INTEGER NOT NULL CHECK(size_bytes BETWEEN 1 AND 2097152),
 sha256 TEXT NOT NULL,uploaded_by BIGINT NOT NULL REFERENCES accounts(id),created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 CHECK(octet_length(content)=size_bytes)
);
CREATE TRIGGER pedagogical_lesson_files_immutable BEFORE UPDATE OR DELETE ON pedagogical_lesson_files FOR EACH ROW EXECUTE FUNCTION reject_work_event_mutation();
CREATE TABLE pedagogical_shares (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,school_id BIGINT NOT NULL REFERENCES organizations(id),
 term_id BIGINT NOT NULL REFERENCES academic_terms(id),teacher_id BIGINT NOT NULL REFERENCES accounts(id),
 scope TEXT NOT NULL CHECK(scope IN ('lesson','period','term')),from_date DATE,to_date DATE,
 status TEXT NOT NULL DEFAULT 'sent' CHECK(status IN ('sent','reviewed','correction_requested','approved')),
 revision INTEGER NOT NULL DEFAULT 1,created_at TIMESTAMPTZ NOT NULL DEFAULT now(),updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 CHECK(from_date IS NULL OR to_date IS NULL OR to_date>=from_date)
);
CREATE TABLE pedagogical_share_items (
