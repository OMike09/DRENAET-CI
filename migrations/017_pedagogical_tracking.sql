CREATE TABLE grade_assessments (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,term_id BIGINT NOT NULL REFERENCES academic_terms(id),
 school_id BIGINT NOT NULL REFERENCES organizations(id),class_id BIGINT NOT NULL REFERENCES academic_classes(id),
 assignment_id BIGINT REFERENCES academic_assignments(id),domain TEXT NOT NULL,
 category_id BIGINT NOT NULL REFERENCES grade_categories(id),lesson_id BIGINT REFERENCES pedagogical_lessons(id),
 legacy_assessment_id BIGINT UNIQUE REFERENCES academic_assessments(id),
 title TEXT NOT NULL,assessed_on DATE NOT NULL,max_score NUMERIC(7,2) NOT NULL CHECK(max_score>0 AND max_score<=1000),
 coefficient NUMERIC(6,2) NOT NULL CHECK(coefficient>0 AND coefficient<=100),
 status TEXT NOT NULL DEFAULT 'draft' CHECK(status IN ('draft','complete','transmitted','pending_validation','validated','locked')),
 revision INTEGER NOT NULL DEFAULT 1,created_by BIGINT NOT NULL REFERENCES accounts(id),created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 transmitted_at TIMESTAMPTZ,validated_by BIGINT REFERENCES accounts(id),validated_at TIMESTAMPTZ,
 rule_revision INTEGER,updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_grade_assessments_term ON grade_assessments(term_id,class_id,assignment_id,status);
CREATE TABLE grade_entries (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,assessment_id BIGINT NOT NULL REFERENCES grade_assessments(id),
