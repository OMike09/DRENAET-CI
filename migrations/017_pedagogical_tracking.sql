 domain TEXT NOT NULL CHECK(domain IN ('pedagogical','conduct')),active BOOLEAN NOT NULL DEFAULT true,
 created_by BIGINT NOT NULL REFERENCES accounts(id),created_at TIMESTAMPTZ NOT NULL DEFAULT now(),UNIQUE(school_id,code)
);
CREATE TABLE grade_rules (
