 weights JSONB NOT NULL,subject_weights JSONB NOT NULL,unjustified_absence TEXT NOT NULL CHECK(unjustified_absence IN ('exclude','zero')),
 justification TEXT NOT NULL,created_by BIGINT NOT NULL REFERENCES accounts(id),created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 UNIQUE(term_id,revision)
