CREATE TABLE IF NOT EXISTS accounts (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 login TEXT NOT NULL UNIQUE,
 full_name TEXT NOT NULL,
 role_key TEXT NOT NULL REFERENCES roles(role_key),
 organization_id BIGINT REFERENCES organizations(id),
 region_id BIGINT REFERENCES organizations(id),
 status TEXT NOT NULL CHECK (status IN ('invited','active','suspended')),
 password_hash TEXT,
 invitation_hash TEXT UNIQUE,
 invitation_expires_at TIMESTAMPTZ,
 auth_version INTEGER NOT NULL DEFAULT 1,
 created_by BIGINT REFERENCES accounts(id),
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 activated_at TIMESTAMPTZ,
 CHECK ((role_key='platform_admin' AND organization_id IS NULL AND region_id IS NULL)
     OR (role_key<>'platform_admin' AND organization_id IS NOT NULL AND region_id IS NOT NULL))
);
CREATE INDEX IF NOT EXISTS idx_accounts_region ON accounts(region_id,organization_id,role_key);

CREATE TABLE IF NOT EXISTS sessions (
 token_hash TEXT PRIMARY KEY,
 account_id BIGINT NOT NULL REFERENCES accounts(id),
 csrf_token TEXT NOT NULL,
 auth_version INTEGER NOT NULL,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 expires_at TIMESTAMPTZ NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_sessions_expiry ON sessions(expires_at);

CREATE TABLE IF NOT EXISTS auth_failures (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 login TEXT NOT NULL,
 ip_hash TEXT NOT NULL,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_auth_failures_window ON auth_failures(login,ip_hash,created_at);

CREATE TABLE IF NOT EXISTS audit_events (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 actor_id BIGINT REFERENCES accounts(id),
 action TEXT NOT NULL,
 target_type TEXT NOT NULL,
 target_id BIGINT,
 region_id BIGINT REFERENCES organizations(id),
 details JSONB NOT NULL DEFAULT '{}'::jsonb,
 ip_hash TEXT,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_audit_events_region ON audit_events(region_id,id DESC);
CREATE OR REPLACE FUNCTION reject_audit_mutation() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN RAISE EXCEPTION 'Le journal d’audit ne peut pas être modifié ou supprimé'; END $$;
DROP TRIGGER IF EXISTS audit_append_only ON audit_events;
CREATE TRIGGER audit_append_only BEFORE UPDATE OR DELETE ON audit_events FOR EACH ROW EXECUTE FUNCTION reject_audit_mutation();
