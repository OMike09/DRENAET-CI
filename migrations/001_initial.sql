-- Étape 1 additive : aucune table héritée n'est effacée ni modifiée.
CREATE TABLE IF NOT EXISTS organizations (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 kind TEXT NOT NULL CHECK (kind IN ('region','school','service')),
 code TEXT NOT NULL UNIQUE,
 name TEXT NOT NULL,
 region_id BIGINT REFERENCES organizations(id),
 status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active','inactive')),
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 CHECK ((kind='region' AND region_id IS NULL) OR (kind<>'region' AND region_id IS NOT NULL))
);
CREATE INDEX IF NOT EXISTS idx_organizations_region ON organizations(region_id,kind);

CREATE TABLE IF NOT EXISTS roles (
 role_key TEXT PRIMARY KEY,
 label TEXT NOT NULL,
 scope TEXT NOT NULL CHECK (scope IN ('platform','region','school','service')),
 rank SMALLINT NOT NULL CHECK (rank BETWEEN 1 AND 100),
 created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
