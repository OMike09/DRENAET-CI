-- Étape 3 additive : messagerie privée et rapports à circuits hiérarchiques versionnés.
CREATE TABLE conversations (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 a_id BIGINT NOT NULL REFERENCES accounts(id),
 b_id BIGINT NOT NULL REFERENCES accounts(id),
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 last_message_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 CHECK(a_id < b_id), UNIQUE(a_id,b_id)
);
CREATE INDEX idx_conversations_a ON conversations(a_id,last_message_at DESC);
CREATE INDEX idx_conversations_b ON conversations(b_id,last_message_at DESC);
CREATE TABLE private_messages (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 conversation_id BIGINT NOT NULL REFERENCES conversations(id),
 sender_id BIGINT NOT NULL REFERENCES accounts(id),
 body TEXT NOT NULL CHECK(length(body) BETWEEN 1 AND 4000),
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 opened_at TIMESTAMPTZ
);
CREATE INDEX idx_private_messages_conversation ON private_messages(conversation_id,id);
CREATE INDEX idx_private_messages_unopened ON private_messages(conversation_id,sender_id) WHERE opened_at IS NULL;
CREATE TABLE report_workflows (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name TEXT NOT NULL,
 description TEXT NOT NULL DEFAULT '',
 region_id BIGINT REFERENCES organizations(id), -- NULL = modèle commun de l'administration générale
 created_by BIGINT NOT NULL REFERENCES accounts(id),
 active BOOLEAN NOT NULL DEFAULT true,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_report_workflows_region ON report_workflows(region_id,id DESC);
CREATE TABLE report_workflow_steps (
 workflow_id BIGINT NOT NULL REFERENCES report_workflows(id),
 position SMALLINT NOT NULL CHECK(position BETWEEN 1 AND 4),
 validator_role TEXT NOT NULL CHECK(validator_role IN ('school_head','regional_director','platform_admin')),
 PRIMARY KEY(workflow_id,position), UNIQUE(workflow_id,validator_role)
);
CREATE TABLE reports (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 workflow_id BIGINT NOT NULL REFERENCES report_workflows(id),
 author_id BIGINT NOT NULL REFERENCES accounts(id),
 region_id BIGINT NOT NULL REFERENCES organizations(id),
 organization_id BIGINT REFERENCES organizations(id),
 subject TEXT NOT NULL,
 status TEXT NOT NULL DEFAULT 'in_review' CHECK(status IN ('in_review','changes_requested','approved')),
 round INTEGER NOT NULL DEFAULT 1 CHECK(round BETWEEN 1 AND 50),
 current_step SMALLINT CHECK(current_step BETWEEN 1 AND 4),
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 approved_at TIMESTAMPTZ
);
CREATE INDEX idx_reports_author ON reports(author_id,id DESC);
CREATE INDEX idx_reports_region ON reports(region_id,id DESC);
CREATE TABLE report_revisions (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 report_id BIGINT NOT NULL REFERENCES reports(id),
 round INTEGER NOT NULL,
 author_id BIGINT NOT NULL REFERENCES accounts(id),
 subject TEXT NOT NULL,
 body TEXT NOT NULL,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 UNIQUE(report_id,round)
);
CREATE TABLE report_stages (
 report_id BIGINT NOT NULL REFERENCES reports(id),
 round INTEGER NOT NULL,
 position SMALLINT NOT NULL CHECK(position BETWEEN 1 AND 4),
 validator_id BIGINT NOT NULL REFERENCES accounts(id),
 validator_role TEXT NOT NULL,
 state TEXT NOT NULL DEFAULT 'waiting' CHECK(state IN ('waiting','active','approved','changes_requested')),
 comment TEXT,
 decided_at TIMESTAMPTZ,
 PRIMARY KEY(report_id,round,position)
);
CREATE INDEX idx_report_stages_validator ON report_stages(validator_id,report_id);
CREATE TABLE report_events (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 report_id BIGINT NOT NULL REFERENCES reports(id),
 round INTEGER NOT NULL,
 actor_id BIGINT NOT NULL REFERENCES accounts(id),
 action TEXT NOT NULL CHECK(action IN ('submit','approve_step','request_changes','resubmit')),
 step_position SMALLINT,
 comment TEXT,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_report_events_report ON report_events(report_id,id);
-- Mutations de contenus et de décisions interdites ; seuls les marqueurs de lecture et l'état courant évoluent.
CREATE TRIGGER private_message_no_rewrite BEFORE UPDATE OF conversation_id,sender_id,body,created_at OR DELETE ON private_messages FOR EACH ROW EXECUTE FUNCTION reject_work_event_mutation();
CREATE TRIGGER workflow_steps_no_rewrite BEFORE UPDATE OR DELETE ON report_workflow_steps FOR EACH ROW EXECUTE FUNCTION reject_work_event_mutation();
CREATE TRIGGER report_revisions_no_rewrite BEFORE UPDATE OR DELETE ON report_revisions FOR EACH ROW EXECUTE FUNCTION reject_work_event_mutation();
CREATE TRIGGER report_events_no_rewrite BEFORE UPDATE OR DELETE ON report_events FOR EACH ROW EXECUTE FUNCTION reject_work_event_mutation();
CREATE OR REPLACE FUNCTION guard_report_stage_update() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF OLD.state IN ('approved','changes_requested') OR NEW.report_id<>OLD.report_id OR NEW.round<>OLD.round OR NEW.position<>OLD.position OR NEW.validator_id<>OLD.validator_id OR NEW.validator_role<>OLD.validator_role OR NOT ((OLD.state='waiting' AND NEW.state='active') OR (OLD.state='active' AND NEW.state IN ('approved','changes_requested'))) THEN
  RAISE EXCEPTION 'Une décision ou affectation de rapport ne peut être modifiée';
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER report_stages_guard BEFORE UPDATE ON report_stages FOR EACH ROW EXECUTE FUNCTION guard_report_stage_update();
CREATE TRIGGER report_stages_no_delete BEFORE DELETE ON report_stages FOR EACH ROW EXECUTE FUNCTION reject_work_event_mutation();
