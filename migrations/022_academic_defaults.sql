CREATE TABLE catalog_levels (
 code TEXT PRIMARY KEY, label TEXT NOT NULL, cycle TEXT NOT NULL, sort_order INTEGER NOT NULL,
 active BOOLEAN NOT NULL DEFAULT true, created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE catalog_subjects (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name TEXT NOT NULL, abbreviation TEXT, domain TEXT NOT NULL, cycle TEXT NOT NULL DEFAULT 'multi',
 active BOOLEAN NOT NULL DEFAULT true, suggested BOOLEAN NOT NULL DEFAULT true,
 created_by BIGINT REFERENCES accounts(id), updated_by BIGINT REFERENCES accounts(id),
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(), updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 CHECK(length(trim(name)) BETWEEN 2 AND 100),CHECK(abbreviation IS NULL OR length(trim(abbreviation)) BETWEEN 1 AND 30)
);
CREATE UNIQUE INDEX catalog_subjects_name_key ON catalog_subjects(lower(btrim(name)));
CREATE TABLE catalog_subject_levels (
 subject_id BIGINT NOT NULL REFERENCES catalog_subjects(id), level_code TEXT NOT NULL REFERENCES catalog_levels(code),
 suggested_coefficient NUMERIC(6,2) CHECK(suggested_coefficient>0 AND suggested_coefficient<=100),
 suggested_weekly_minutes INTEGER CHECK(suggested_weekly_minutes BETWEEN 20 AND 2400),
 PRIMARY KEY(subject_id,level_code)
);
CREATE TABLE catalog_evaluation_types (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,code TEXT NOT NULL UNIQUE,label TEXT NOT NULL UNIQUE,
 active BOOLEAN NOT NULL DEFAULT true,default_max_score NUMERIC(7,2) CHECK(default_max_score>0 AND default_max_score<=1000),
 default_coefficient NUMERIC(6,2) CHECK(default_coefficient>0 AND default_coefficient<=100),
 created_by BIGINT REFERENCES accounts(id),updated_by BIGINT REFERENCES accounts(id),updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE catalog_reference_items (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,category TEXT NOT NULL,code TEXT NOT NULL,label TEXT NOT NULL,
 active BOOLEAN NOT NULL DEFAULT true,created_by BIGINT REFERENCES accounts(id),updated_by BIGINT REFERENCES accounts(id),
 updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),UNIQUE(category,code)
);
CREATE UNIQUE INDEX catalog_reference_item_name ON catalog_reference_items(category,lower(btrim(label)));
CREATE TABLE academic_class_programs (
 class_id BIGINT PRIMARY KEY REFERENCES academic_classes(id),level_code TEXT REFERENCES catalog_levels(code),
 series TEXT NOT NULL DEFAULT '',track TEXT NOT NULL DEFAULT '',updated_by BIGINT REFERENCES accounts(id),updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE academic_class_subjects (
 class_id BIGINT NOT NULL REFERENCES academic_classes(id),subject_id BIGINT NOT NULL REFERENCES catalog_subjects(id),
 coefficient NUMERIC(6,2) CHECK(coefficient>0 AND coefficient<=100),weekly_minutes INTEGER CHECK(weekly_minutes BETWEEN 20 AND 2400),
 added_by BIGINT NOT NULL REFERENCES accounts(id),added_at TIMESTAMPTZ NOT NULL DEFAULT now(),PRIMARY KEY(class_id,subject_id)
);
