-- Catégories facultatives des dossiers existants : n'interfèrent jamais avec les états techniques.
CREATE TABLE catalog_reference_uses (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 entity_type TEXT NOT NULL CHECK(entity_type IN ('courier','announcement','report','training','task','meeting','absence','attendance_justification')),
 entity_id BIGINT NOT NULL CHECK(entity_id>0),category TEXT NOT NULL,
 reference_id BIGINT NOT NULL REFERENCES catalog_reference_items(id),
 chosen_by BIGINT NOT NULL REFERENCES accounts(id),created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX catalog_reference_uses_lookup ON catalog_reference_uses(entity_type,entity_id,id DESC);
CREATE OR REPLACE FUNCTION guard_catalog_reference_use() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF NOT EXISTS(SELECT 1 FROM catalog_reference_items WHERE id=NEW.reference_id AND category=NEW.category AND active) THEN RAISE EXCEPTION 'Classification absente ou désactivée'; END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER catalog_reference_uses_guard BEFORE INSERT ON catalog_reference_uses FOR EACH ROW EXECUTE FUNCTION guard_catalog_reference_use();
CREATE TRIGGER catalog_reference_uses_immutable BEFORE UPDATE OR DELETE ON catalog_reference_uses FOR EACH ROW EXECUTE FUNCTION reject_work_event_mutation();
