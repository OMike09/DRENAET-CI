CREATE TABLE announcement_delegations (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 publisher_id BIGINT NOT NULL REFERENCES accounts(id), recipient_id BIGINT NOT NULL REFERENCES accounts(id),
 granted_by BIGINT NOT NULL REFERENCES accounts(id), granted_at TIMESTAMPTZ NOT NULL DEFAULT now(), revoked_at TIMESTAMPTZ,
 UNIQUE(publisher_id,recipient_id), CHECK(publisher_id<>recipient_id)
);
CREATE TABLE official_announcements (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, author_id BIGINT NOT NULL REFERENCES accounts(id),
 title TEXT NOT NULL, content TEXT NOT NULL,
 category TEXT NOT NULL CHECK(category IN ('general','administrative','pedagogical','convocation','meeting','decision','service_note','urgent','other')),
 priority TEXT NOT NULL CHECK(priority IN ('normal','high','urgent')),
 status TEXT NOT NULL DEFAULT 'draft' CHECK(status IN ('draft','published','archived')),
 selection JSONB NOT NULL DEFAULT '{}'::jsonb,
 visible_from TIMESTAMPTZ, visible_until TIMESTAMPTZ, acknowledgement_deadline TIMESTAMPTZ,
 ack_required BOOLEAN NOT NULL DEFAULT false,
 published_at TIMESTAMPTZ, archived_at TIMESTAMPTZ, version INTEGER NOT NULL DEFAULT 1,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(), updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 CHECK(visible_from IS NULL OR visible_until IS NULL OR visible_until>visible_from)
);
CREATE INDEX idx_announcements_author ON official_announcements(author_id,id DESC);
CREATE TABLE announcement_recipients (
 announcement_id BIGINT NOT NULL REFERENCES official_announcements(id), account_id BIGINT NOT NULL REFERENCES accounts(id),
 delivered_at TIMESTAMPTZ NOT NULL DEFAULT now(), first_opened_at TIMESTAMPTZ, last_opened_at TIMESTAMPTZ,
 view_count INTEGER NOT NULL DEFAULT 0 CHECK(view_count>=0), acknowledged_at TIMESTAMPTZ,
 PRIMARY KEY(announcement_id,account_id), CHECK(acknowledged_at IS NULL OR first_opened_at IS NOT NULL)
);
CREATE INDEX idx_announcement_recipient_account ON announcement_recipients(account_id,announcement_id);
CREATE TABLE announcement_events (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 announcement_id BIGINT NOT NULL REFERENCES official_announcements(id), actor_id BIGINT NOT NULL REFERENCES accounts(id),
 action TEXT NOT NULL, details JSONB NOT NULL DEFAULT '{}'::jsonb, created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TRIGGER announcement_events_immutable BEFORE UPDATE OR DELETE ON announcement_events FOR EACH ROW EXECUTE FUNCTION reject_work_event_mutation();
CREATE TABLE announcement_reminders (
 announcement_id BIGINT NOT NULL REFERENCES official_announcements(id), account_id BIGINT NOT NULL REFERENCES accounts(id),
 phase TEXT NOT NULL, sent_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 PRIMARY KEY(announcement_id,account_id,phase)
);
CREATE TABLE teacher_requests (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, teacher_id BIGINT NOT NULL REFERENCES accounts(id),
 head_id BIGINT NOT NULL REFERENCES accounts(id), assignee_id BIGINT NOT NULL REFERENCES accounts(id),
 region_id BIGINT NOT NULL REFERENCES organizations(id), school_id BIGINT NOT NULL REFERENCES organizations(id),
 category TEXT NOT NULL CHECK(category IN ('administrative','authorization','document','difficulty','equipment','appointment','other')),
 subject TEXT NOT NULL, description TEXT NOT NULL, priority TEXT NOT NULL CHECK(priority IN ('normal','high','urgent')),
 status TEXT NOT NULL CHECK(status IN ('sent','received','processing','waiting','accepted','rejected','closed')),
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(), updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_teacher_requests_teacher ON teacher_requests(teacher_id,id DESC);
CREATE INDEX idx_teacher_requests_assignee ON teacher_requests(assignee_id,id DESC);
CREATE TABLE teacher_request_events (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, request_id BIGINT NOT NULL REFERENCES teacher_requests(id),
 actor_id BIGINT NOT NULL REFERENCES accounts(id), action TEXT NOT NULL, note TEXT,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TRIGGER teacher_request_events_immutable BEFORE UPDATE OR DELETE ON teacher_request_events FOR EACH ROW EXECUTE FUNCTION reject_work_event_mutation();
