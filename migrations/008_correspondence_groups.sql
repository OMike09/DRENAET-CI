-- Colis 8 additif : registre, transmissions, groupes et messages ; anciens contenus inchangés.
CREATE TABLE correspondence_records (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 direction TEXT NOT NULL CHECK(direction IN ('incoming','outgoing')),
 scope TEXT NOT NULL CHECK(scope IN ('platform','region','school')),
 region_id BIGINT REFERENCES organizations(id),
 organization_id BIGINT REFERENCES organizations(id),
 created_by BIGINT NOT NULL REFERENCES accounts(id),
 external_reference TEXT NOT NULL,
 subject TEXT NOT NULL,
 correspondent TEXT NOT NULL,
 summary TEXT NOT NULL,
 document_date DATE NOT NULL,
 status TEXT NOT NULL DEFAULT 'registered' CHECK(status IN ('registered','pending','received','closed')),
 current_holder_id BIGINT REFERENCES accounts(id),
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 CHECK ((scope='platform' AND region_id IS NULL AND organization_id IS NULL) OR (scope='region' AND region_id IS NOT NULL AND organization_id IS NULL) OR (scope='school' AND region_id IS NOT NULL AND organization_id IS NOT NULL))
);
CREATE INDEX idx_correspondence_scope ON correspondence_records(scope,region_id,organization_id,id DESC);
CREATE TRIGGER correspondence_no_delete BEFORE DELETE ON correspondence_records FOR EACH ROW EXECUTE FUNCTION reject_work_event_mutation();
CREATE OR REPLACE FUNCTION guard_correspondence_update() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF NEW.id<>OLD.id OR NEW.direction<>OLD.direction OR NEW.scope<>OLD.scope OR NEW.region_id IS DISTINCT FROM OLD.region_id OR NEW.organization_id IS DISTINCT FROM OLD.organization_id OR NEW.created_by<>OLD.created_by OR NEW.external_reference<>OLD.external_reference OR NEW.subject<>OLD.subject OR NEW.correspondent<>OLD.correspondent OR NEW.summary<>OLD.summary OR NEW.document_date<>OLD.document_date OR NEW.created_at<>OLD.created_at OR NEW.updated_at<OLD.updated_at OR NOT ((OLD.status='registered' AND NEW.status IN ('pending','closed')) OR (OLD.status='pending' AND NEW.status='received' AND NEW.current_holder_id=OLD.current_holder_id) OR (OLD.status='received' AND NEW.status IN ('pending','closed'))) THEN
  RAISE EXCEPTION 'Un courrier enregistré ne peut être réécrit';
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER correspondence_guard BEFORE UPDATE ON correspondence_records FOR EACH ROW EXECUTE FUNCTION guard_correspondence_update();
CREATE TABLE correspondence_events (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 record_id BIGINT NOT NULL REFERENCES correspondence_records(id),
 actor_id BIGINT NOT NULL REFERENCES accounts(id),
 recipient_id BIGINT REFERENCES accounts(id),
 action TEXT NOT NULL CHECK(action IN ('register','transmit','receipt','close')),
 note TEXT,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_correspondence_events ON correspondence_events(record_id,id);
CREATE TRIGGER correspondence_events_no_rewrite BEFORE UPDATE OR DELETE ON correspondence_events FOR EACH ROW EXECUTE FUNCTION reject_work_event_mutation();
CREATE TABLE message_groups (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name TEXT NOT NULL,
 scope TEXT NOT NULL CHECK(scope IN ('platform','region','school')),
 region_id BIGINT REFERENCES organizations(id),
 organization_id BIGINT REFERENCES organizations(id),
 created_by BIGINT NOT NULL REFERENCES accounts(id),
 last_message_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 CHECK ((scope='platform' AND region_id IS NULL AND organization_id IS NULL) OR (scope='region' AND region_id IS NOT NULL AND organization_id IS NULL) OR (scope='school' AND region_id IS NOT NULL AND organization_id IS NOT NULL))
);
CREATE TRIGGER message_groups_no_delete BEFORE DELETE ON message_groups FOR EACH ROW EXECUTE FUNCTION reject_work_event_mutation();
CREATE OR REPLACE FUNCTION guard_message_group_update() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF NEW.id<>OLD.id OR NEW.name<>OLD.name OR NEW.scope<>OLD.scope OR NEW.region_id IS DISTINCT FROM OLD.region_id OR NEW.organization_id IS DISTINCT FROM OLD.organization_id OR NEW.created_by<>OLD.created_by OR NEW.created_at<>OLD.created_at OR NEW.last_message_at<OLD.last_message_at THEN
  RAISE EXCEPTION 'Un groupe ne peut être réécrit';
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER message_groups_guard BEFORE UPDATE ON message_groups FOR EACH ROW EXECUTE FUNCTION guard_message_group_update();
CREATE TABLE message_group_members (
 group_id BIGINT NOT NULL REFERENCES message_groups(id),
 account_id BIGINT NOT NULL REFERENCES accounts(id),
 active BOOLEAN NOT NULL DEFAULT true,
 joined_after_id BIGINT NOT NULL DEFAULT 0,
 last_read_id BIGINT NOT NULL DEFAULT 0,
 joined_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 left_at TIMESTAMPTZ,
 PRIMARY KEY(group_id,account_id)
);
CREATE INDEX idx_group_members_account ON message_group_members(account_id,group_id);
CREATE TABLE message_group_events (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 group_id BIGINT NOT NULL REFERENCES message_groups(id),
 actor_id BIGINT NOT NULL REFERENCES accounts(id),
 account_id BIGINT NOT NULL REFERENCES accounts(id),
 action TEXT NOT NULL CHECK(action IN ('add','remove','rejoin')),
 created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TRIGGER message_group_events_no_rewrite BEFORE UPDATE OR DELETE ON message_group_events FOR EACH ROW EXECUTE FUNCTION reject_work_event_mutation();
CREATE TABLE message_group_messages (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 group_id BIGINT NOT NULL REFERENCES message_groups(id),
 sender_id BIGINT NOT NULL REFERENCES accounts(id),
 body TEXT NOT NULL,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_group_messages ON message_group_messages(group_id,id DESC);
CREATE TRIGGER message_group_messages_no_rewrite BEFORE UPDATE OR DELETE ON message_group_messages FOR EACH ROW EXECUTE FUNCTION reject_work_event_mutation();
