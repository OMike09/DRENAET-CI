CREATE TABLE attendance_delegations (
 manager_id BIGINT NOT NULL REFERENCES accounts(id),
 action TEXT NOT NULL CHECK(action IN ('view','clock','configure','review','correct','export')),
 granted_by BIGINT NOT NULL REFERENCES accounts(id), granted_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 revoked_at TIMESTAMPTZ, revoked_by BIGINT REFERENCES accounts(id),
 PRIMARY KEY(manager_id,action)
);
CREATE TABLE attendance_groups (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 organization_id BIGINT NOT NULL REFERENCES organizations(id),
 name TEXT NOT NULL, active BOOLEAN NOT NULL DEFAULT true,
 created_by BIGINT NOT NULL REFERENCES accounts(id),created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 UNIQUE(organization_id,name)
);
CREATE TABLE attendance_group_members (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 group_id BIGINT NOT NULL REFERENCES attendance_groups(id), account_id BIGINT NOT NULL REFERENCES accounts(id),
 starts_on DATE NOT NULL, ends_on DATE,
 assigned_by BIGINT NOT NULL REFERENCES accounts(id), assigned_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 CHECK(ends_on IS NULL OR ends_on>=starts_on),UNIQUE(group_id,account_id,starts_on)
);
CREATE INDEX attendance_members_account ON attendance_group_members(account_id,starts_on,ends_on);
CREATE TABLE attendance_schedules (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 scope TEXT NOT NULL CHECK(scope IN ('platform','region','organization','group','person','exception')),
 region_id BIGINT REFERENCES organizations(id), organization_id BIGINT REFERENCES organizations(id),
 group_id BIGINT REFERENCES attendance_groups(id), person_id BIGINT REFERENCES accounts(id),
 weekday SMALLINT CHECK(weekday BETWEEN 1 AND 7),
 effective_from DATE NOT NULL, effective_until DATE,
 working BOOLEAN NOT NULL,
 start_min SMALLINT CHECK(start_min BETWEEN 0 AND 1439),
 earliest_min SMALLINT NOT NULL CHECK(earliest_min BETWEEN 0 AND 1439),
 latest_min SMALLINT NOT NULL CHECK(latest_min BETWEEN 0 AND 1439),
 author_id BIGINT NOT NULL REFERENCES accounts(id),reason TEXT NOT NULL,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 CHECK(effective_until IS NULL OR effective_until>=effective_from),
 CHECK(earliest_min<=latest_min AND (NOT working OR start_min BETWEEN earliest_min AND latest_min)),
 CHECK((scope='platform' AND region_id IS NULL AND organization_id IS NULL AND group_id IS NULL AND person_id IS NULL)
 OR (scope='region' AND region_id IS NOT NULL AND organization_id IS NULL AND group_id IS NULL AND person_id IS NULL)
 OR (scope='organization' AND organization_id IS NOT NULL AND group_id IS NULL AND person_id IS NULL)
 OR (scope='group' AND organization_id IS NOT NULL AND group_id IS NOT NULL AND person_id IS NULL)
 OR (scope IN ('person','exception') AND organization_id IS NOT NULL AND person_id IS NOT NULL AND group_id IS NULL)),
 CHECK(scope='exception' OR weekday IS NOT NULL)
);
CREATE INDEX attendance_schedules_lookup ON attendance_schedules(scope,organization_id,person_id,weekday,effective_from DESC,id DESC);
CREATE TRIGGER attendance_schedules_immutable BEFORE UPDATE OR DELETE ON attendance_schedules FOR EACH ROW EXECUTE FUNCTION reject_work_event_mutation();
CREATE TABLE attendance_thresholds (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 scope TEXT NOT NULL CHECK(scope IN ('platform','region','organization','group','person')),
 region_id BIGINT REFERENCES organizations(id), organization_id BIGINT REFERENCES organizations(id),
 group_id BIGINT REFERENCES attendance_groups(id),person_id BIGINT REFERENCES accounts(id),
 effective_from DATE NOT NULL,light_until SMALLINT NOT NULL,serious_until SMALLINT NOT NULL,grave_until SMALLINT NOT NULL,
 light_min SMALLINT NOT NULL,light_max SMALLINT NOT NULL,
 serious_min SMALLINT NOT NULL,serious_max SMALLINT NOT NULL,
 grave_min SMALLINT NOT NULL,grave_max SMALLINT NOT NULL,
 author_id BIGINT REFERENCES accounts(id),reason TEXT NOT NULL,created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 CHECK(1<=light_until AND light_until<serious_until AND serious_until<grave_until),
 CHECK(light_min<=light_until AND light_until<=light_max AND serious_min<=serious_until AND serious_until<=serious_max AND grave_min<=grave_until AND grave_until<=grave_max),
 CHECK((scope='platform' AND region_id IS NULL AND organization_id IS NULL AND group_id IS NULL AND person_id IS NULL) OR (scope='region' AND region_id IS NOT NULL AND organization_id IS NULL AND group_id IS NULL AND person_id IS NULL) OR (scope='organization' AND organization_id IS NOT NULL AND group_id IS NULL AND person_id IS NULL) OR (scope='group' AND organization_id IS NOT NULL AND group_id IS NOT NULL AND person_id IS NULL) OR (scope='person' AND organization_id IS NOT NULL AND person_id IS NOT NULL AND group_id IS NULL))
);
CREATE INDEX attendance_thresholds_lookup ON attendance_thresholds(scope,organization_id,region_id,effective_from DESC,id DESC);
CREATE TRIGGER attendance_thresholds_immutable BEFORE UPDATE OR DELETE ON attendance_thresholds FOR EACH ROW EXECUTE FUNCTION reject_work_event_mutation();
