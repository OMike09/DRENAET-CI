CREATE TABLE attendance_records (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 person_id BIGINT NOT NULL REFERENCES accounts(id),day DATE NOT NULL,
 person_name TEXT NOT NULL,person_role TEXT NOT NULL,person_phone TEXT,
 organization_id BIGINT NOT NULL REFERENCES organizations(id),region_id BIGINT REFERENCES organizations(id),
 schedule_id BIGINT NOT NULL REFERENCES attendance_schedules(id),threshold_id BIGINT NOT NULL REFERENCES attendance_thresholds(id),
 start_min SMALLINT NOT NULL, arrival_min SMALLINT NOT NULL,delay_minutes SMALLINT NOT NULL CHECK(delay_minutes BETWEEN 0 AND 1439),
 severity TEXT NOT NULL CHECK(severity IN ('on_time','light','serious','grave','very_grave')),
 recorded_by BIGINT NOT NULL REFERENCES accounts(id),recorded_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 manual_reason TEXT,revision INTEGER NOT NULL DEFAULT 1,updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 UNIQUE(person_id,day)
);
CREATE INDEX attendance_records_scope ON attendance_records(region_id,organization_id,day DESC);
CREATE TABLE attendance_record_events (
