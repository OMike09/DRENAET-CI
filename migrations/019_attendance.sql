 recorded_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TRIGGER attendance_record_events_immutable BEFORE UPDATE OR DELETE ON attendance_record_events FOR EACH ROW EXECUTE FUNCTION reject_work_event_mutation();
CREATE TABLE attendance_justifications (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 person_id BIGINT NOT NULL REFERENCES accounts(id),day DATE NOT NULL,
 organization_id BIGINT NOT NULL REFERENCES organizations(id),region_id BIGINT REFERENCES organizations(id),
 declared_arrival_min SMALLINT CHECK(declared_arrival_min BETWEEN 0 AND 1439),
 category TEXT NOT NULL CHECK(category IN ('rain','transport','traffic','incident','authorization','other')),
 explanation TEXT NOT NULL,status TEXT NOT NULL DEFAULT 'submitted' CHECK(status IN ('submitted','pending','more_info','accepted','rejected')),
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),decided_at TIMESTAMPTZ,decided_by BIGINT REFERENCES accounts(id),decision_note TEXT,
 revision INTEGER NOT NULL DEFAULT 1,UNIQUE(person_id,day)
);
CREATE TABLE attendance_justification_files (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
