 content BYTEA NOT NULL,size_bytes INTEGER NOT NULL CHECK(size_bytes BETWEEN 8 AND 2097152),
 sha256 TEXT NOT NULL,uploaded_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 CHECK(octet_length(content)=size_bytes)
);
CREATE TRIGGER attendance_justification_files_immutable BEFORE UPDATE OR DELETE ON attendance_justification_files FOR EACH ROW EXECUTE FUNCTION reject_work_event_mutation();
