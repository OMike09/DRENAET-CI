CREATE TABLE academic_years (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 label TEXT NOT NULL CHECK(label ~ '^[0-9]{4}-[0-9]{4}$'),
 scope TEXT NOT NULL CHECK(scope IN ('platform','region','school')),
 region_id BIGINT REFERENCES organizations(id), school_id BIGINT REFERENCES organizations(id),
 parent_id BIGINT REFERENCES academic_years(id),
 starts_on DATE NOT NULL, ends_on DATE NOT NULL, periods SMALLINT NOT NULL DEFAULT 3 CHECK(periods BETWEEN 1 AND 6),
 status TEXT NOT NULL DEFAULT 'planned' CHECK(status IN ('planned','active','closed','archived')),
 created_by BIGINT NOT NULL REFERENCES accounts(id), created_at TIMESTAMPTZ NOT NULL DEFAULT now(), updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 CHECK(ends_on>starts_on),
 CHECK((scope='platform' AND region_id IS NULL AND school_id IS NULL AND parent_id IS NULL) OR
 (scope='region' AND region_id IS NOT NULL AND school_id IS NULL AND parent_id IS NOT NULL) OR
 (scope='school' AND region_id IS NOT NULL AND school_id IS NOT NULL AND parent_id IS NOT NULL)),
 UNIQUE(label,scope,region_id,school_id)
);
CREATE UNIQUE INDEX uq_academic_years_scope ON academic_years(label,scope,coalesce(region_id,0),coalesce(school_id,0));
CREATE UNIQUE INDEX uq_academic_years_active ON academic_years(scope,coalesce(region_id,0),coalesce(school_id,0)) WHERE status='active';
CREATE TABLE academic_terms (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 year_id BIGINT NOT NULL REFERENCES academic_years(id),
 ordinal SMALLINT NOT NULL CHECK(ordinal BETWEEN 1 AND 6), name TEXT NOT NULL,
 starts_on DATE NOT NULL, ends_on DATE NOT NULL, evaluation_opens_on DATE NOT NULL, evaluation_closes_on DATE NOT NULL,
 composition_starts_on DATE NOT NULL, composition_ends_on DATE NOT NULL,
 notes_deadline_on DATE NOT NULL, validation_on DATE NOT NULL, final_close_on DATE NOT NULL,
 status TEXT NOT NULL DEFAULT 'planned' CHECK(status IN ('planned','open','suspended','evaluations_closed','closed','archived')),
 exception_until TIMESTAMPTZ,
 revision INTEGER NOT NULL DEFAULT 1,
 opened_at TIMESTAMPTZ, closed_at TIMESTAMPTZ,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(), updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 UNIQUE(year_id,ordinal), CHECK(ends_on>=starts_on),
 CHECK(starts_on<=evaluation_opens_on AND evaluation_opens_on<=evaluation_closes_on AND evaluation_closes_on<=ends_on),
 CHECK(starts_on<=composition_starts_on AND composition_starts_on<=composition_ends_on AND composition_ends_on<=ends_on),
 CHECK(evaluation_closes_on<=notes_deadline_on AND notes_deadline_on<=validation_on AND validation_on<=final_close_on)
);
CREATE INDEX idx_academic_terms_year ON academic_terms(year_id,ordinal);
CREATE UNIQUE INDEX uq_academic_current_term ON academic_terms(year_id) WHERE status IN ('open','suspended','evaluations_closed');
CREATE TABLE academic_delegations (
 school_id BIGINT NOT NULL REFERENCES organizations(id), ace_id BIGINT NOT NULL REFERENCES accounts(id),
 can_manage BOOLEAN NOT NULL DEFAULT false, can_cosign BOOLEAN NOT NULL DEFAULT false,
 granted_by BIGINT NOT NULL REFERENCES accounts(id), role_at_grant TEXT NOT NULL, organization_at_grant BIGINT NOT NULL REFERENCES organizations(id),
 revoked_at TIMESTAMPTZ, updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 PRIMARY KEY(school_id,ace_id), CHECK(can_manage OR can_cosign)
);
CREATE TABLE academic_events (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, term_id BIGINT NOT NULL REFERENCES academic_terms(id),
 school_id BIGINT NOT NULL REFERENCES organizations(id), class_id BIGINT, assignment_id BIGINT,
 kind TEXT NOT NULL CHECK(kind IN ('timetable','supervision','composition','meeting','class_council','administrative')),
 title TEXT NOT NULL, description TEXT NOT NULL DEFAULT '', location TEXT NOT NULL DEFAULT '',
 starts_at TIMESTAMPTZ NOT NULL, ends_at TIMESTAMPTZ NOT NULL,
 created_by BIGINT NOT NULL REFERENCES accounts(id), created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 CHECK(ends_at>starts_at)
);
CREATE TABLE academic_classes (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 year_id BIGINT NOT NULL REFERENCES academic_years(id), school_id BIGINT NOT NULL REFERENCES organizations(id),
 name TEXT NOT NULL, created_by BIGINT NOT NULL REFERENCES accounts(id), created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 UNIQUE(year_id,school_id,name)
);
ALTER TABLE academic_events ADD CONSTRAINT academic_events_class_fk FOREIGN KEY(class_id) REFERENCES academic_classes(id);
CREATE TABLE academic_pupils (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 class_id BIGINT NOT NULL REFERENCES academic_classes(id), full_name TEXT NOT NULL, registration_code TEXT,
 created_by BIGINT NOT NULL REFERENCES accounts(id), created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 UNIQUE(class_id,registration_code)
);
CREATE TABLE academic_assignments (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 class_id BIGINT NOT NULL REFERENCES academic_classes(id), teacher_id BIGINT NOT NULL REFERENCES accounts(id),
 subject TEXT NOT NULL, created_by BIGINT NOT NULL REFERENCES accounts(id), created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 UNIQUE(class_id,subject,teacher_id)
);
ALTER TABLE academic_events ADD CONSTRAINT academic_events_assignment_fk FOREIGN KEY(assignment_id) REFERENCES academic_assignments(id);
CREATE INDEX idx_academic_assignments_teacher ON academic_assignments(teacher_id,class_id);
CREATE TABLE academic_assessments (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 term_id BIGINT NOT NULL REFERENCES academic_terms(id), assignment_id BIGINT NOT NULL REFERENCES academic_assignments(id),
 kind TEXT NOT NULL CHECK(kind IN ('homework','composition')), title TEXT NOT NULL,
 occurs_at TIMESTAMPTZ NOT NULL, coefficient NUMERIC(5,2) NOT NULL DEFAULT 1 CHECK(coefficient>0 AND coefficient<=20),
 created_by BIGINT NOT NULL REFERENCES accounts(id), created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE academic_marks (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 assessment_id BIGINT NOT NULL REFERENCES academic_assessments(id), pupil_id BIGINT NOT NULL REFERENCES academic_pupils(id),
 score NUMERIC(5,2) NOT NULL CHECK(score BETWEEN 0 AND 20), revision INTEGER NOT NULL DEFAULT 1,
 entered_by BIGINT NOT NULL REFERENCES accounts(id), updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 UNIQUE(assessment_id,pupil_id)
);
CREATE TABLE academic_mark_revisions (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 mark_id BIGINT NOT NULL REFERENCES academic_marks(id), revision INTEGER NOT NULL,
 score NUMERIC(5,2) NOT NULL CHECK(score BETWEEN 0 AND 20),
 actor_id BIGINT NOT NULL REFERENCES accounts(id), reason TEXT NOT NULL,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(), UNIQUE(mark_id,revision)
);
CREATE TRIGGER academic_mark_revisions_immutable BEFORE UPDATE OR DELETE ON academic_mark_revisions FOR EACH ROW EXECUTE FUNCTION reject_work_event_mutation();
CREATE TRIGGER academic_marks_no_delete BEFORE DELETE ON academic_marks FOR EACH ROW EXECUTE FUNCTION reject_work_event_mutation();
CREATE TABLE academic_lessons (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 term_id BIGINT NOT NULL REFERENCES academic_terms(id), assignment_id BIGINT NOT NULL REFERENCES academic_assignments(id),
 taught_on DATE NOT NULL, content TEXT NOT NULL, progress_percent SMALLINT CHECK(progress_percent BETWEEN 0 AND 100),
 created_by BIGINT NOT NULL REFERENCES accounts(id), created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE academic_reports (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 term_id BIGINT NOT NULL REFERENCES academic_terms(id), school_id BIGINT NOT NULL REFERENCES organizations(id),
 class_id BIGINT REFERENCES academic_classes(id), title TEXT NOT NULL, due_on DATE NOT NULL,
 content TEXT, submitted_at TIMESTAMPTZ, created_by BIGINT NOT NULL REFERENCES accounts(id)
);
CREATE TABLE academic_actions (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 term_id BIGINT REFERENCES academic_terms(id), year_id BIGINT REFERENCES academic_years(id),
 actor_id BIGINT NOT NULL REFERENCES accounts(id), action TEXT NOT NULL,
 reason TEXT, details JSONB NOT NULL DEFAULT '{}'::jsonb,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 CHECK(term_id IS NOT NULL OR year_id IS NOT NULL)
);
CREATE TRIGGER academic_actions_immutable BEFORE UPDATE OR DELETE ON academic_actions FOR EACH ROW EXECUTE FUNCTION reject_work_event_mutation();
CREATE TABLE academic_proposals (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, term_id BIGINT NOT NULL REFERENCES academic_terms(id),
 action TEXT NOT NULL CHECK(action IN ('close','reopen')),
 proposed_by BIGINT NOT NULL REFERENCES accounts(id), reason TEXT NOT NULL,
 exception_until TIMESTAMPTZ, term_revision INTEGER NOT NULL,
 status TEXT NOT NULL DEFAULT 'pending' CHECK(status IN ('pending','approved','rejected')),
 signed_by BIGINT REFERENCES accounts(id), reviewed_at TIMESTAMPTZ,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX uq_academic_pending_action ON academic_proposals(term_id) WHERE status='pending';
ALTER TABLE activity_notifications DROP CONSTRAINT activity_notifications_entity_type_check;
ALTER TABLE activity_notifications ADD CONSTRAINT activity_notifications_entity_type_check CHECK(entity_type IN ('message','report','library','calendar','group','correspondence','reminder_instruction','reminder_task','reminder_calendar','training','announcement','teacher_request','academic_term'));
