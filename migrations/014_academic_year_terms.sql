CREATE TABLE academic_term_views (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 term_id BIGINT NOT NULL REFERENCES academic_terms(id), revision INTEGER NOT NULL,
 account_id BIGINT NOT NULL REFERENCES accounts(id), viewed_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_academic_term_views_followup ON academic_term_views(term_id,revision,account_id);
CREATE TRIGGER academic_term_views_immutable BEFORE UPDATE OR DELETE ON academic_term_views FOR EACH ROW EXECUTE FUNCTION reject_work_event_mutation();
CREATE TABLE academic_term_acks (
 term_id BIGINT NOT NULL REFERENCES academic_terms(id), revision INTEGER NOT NULL,
 account_id BIGINT NOT NULL REFERENCES accounts(id), acknowledged_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 PRIMARY KEY(term_id,revision,account_id)
);
CREATE TRIGGER academic_term_acks_immutable BEFORE UPDATE OR DELETE ON academic_term_acks FOR EACH ROW EXECUTE FUNCTION reject_work_event_mutation();
