-- Étape 2 additive : instructions, missions, événements et alertes internes.
CREATE TABLE IF NOT EXISTS instructions (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 issuer_id BIGINT NOT NULL REFERENCES accounts(id),
 region_id BIGINT REFERENCES organizations(id),
 subject TEXT NOT NULL,
 description TEXT NOT NULL,
 priority TEXT NOT NULL CHECK(priority IN ('normal','high','urgent')),
 due_at TIMESTAMPTZ,
 parent_instruction_id BIGINT REFERENCES instructions(id),
 issued_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 CHECK (due_at IS NULL OR due_at>issued_at)
);
CREATE INDEX IF NOT EXISTS idx_instructions_issuer ON instructions(issuer_id,id DESC);
CREATE TABLE IF NOT EXISTS instruction_recipients (
 instruction_id BIGINT NOT NULL REFERENCES instructions(id),
 recipient_id BIGINT NOT NULL REFERENCES accounts(id),
 state TEXT NOT NULL DEFAULT 'new' CHECK(state IN ('new','received','viewed','in_progress','waiting','forwarded','executed','validated','rejected')),
 received_at TIMESTAMPTZ,
 viewed_at TIMESTAMPTZ,
 executed_at TIMESTAMPTZ,
 validated_at TIMESTAMPTZ,
 updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 PRIMARY KEY(instruction_id,recipient_id)
);
CREATE INDEX IF NOT EXISTS idx_instruction_recipient ON instruction_recipients(recipient_id,instruction_id DESC);
CREATE TABLE IF NOT EXISTS instruction_events (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 instruction_id BIGINT NOT NULL REFERENCES instructions(id),
 recipient_id BIGINT NOT NULL REFERENCES accounts(id),
 actor_id BIGINT NOT NULL REFERENCES accounts(id),
 action TEXT NOT NULL,
 previous_state TEXT,
 next_state TEXT,
 message TEXT,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_instruction_events ON instruction_events(instruction_id,id);
CREATE TABLE IF NOT EXISTS tasks (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 issuer_id BIGINT NOT NULL REFERENCES accounts(id),
 assignee_id BIGINT NOT NULL REFERENCES accounts(id),
 region_id BIGINT REFERENCES organizations(id),
 title TEXT NOT NULL,
 description TEXT NOT NULL,
 start_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 due_at TIMESTAMPTZ,
 priority TEXT NOT NULL CHECK(priority IN ('normal','high','urgent')),
 progress SMALLINT NOT NULL DEFAULT 0 CHECK(progress BETWEEN 0 AND 100),
 state TEXT NOT NULL DEFAULT 'assigned' CHECK(state IN ('assigned','received','in_progress','waiting','submitted','validated','rejected')),
 viewed_at TIMESTAMPTZ,
 final_report TEXT,
 completed_at TIMESTAMPTZ,
 validated_at TIMESTAMPTZ,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 CHECK (due_at IS NULL OR due_at>start_at)
);
CREATE INDEX IF NOT EXISTS idx_tasks_issuer ON tasks(issuer_id,id DESC);
CREATE INDEX IF NOT EXISTS idx_tasks_assignee ON tasks(assignee_id,id DESC);
CREATE TABLE IF NOT EXISTS task_collaborators (
 task_id BIGINT NOT NULL REFERENCES tasks(id),
 account_id BIGINT NOT NULL REFERENCES accounts(id),
 PRIMARY KEY(task_id,account_id)
);
CREATE INDEX IF NOT EXISTS idx_task_collaborators_account ON task_collaborators(account_id,task_id DESC);
CREATE TABLE IF NOT EXISTS task_events (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 task_id BIGINT NOT NULL REFERENCES tasks(id),
 actor_id BIGINT NOT NULL REFERENCES accounts(id),
 action TEXT NOT NULL,
 previous_state TEXT,
 next_state TEXT,
 message TEXT,
 progress SMALLINT,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_task_events ON task_events(task_id,id);
CREATE TABLE IF NOT EXISTS work_notifications (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id BIGINT NOT NULL REFERENCES accounts(id),
 kind TEXT NOT NULL,
 entity_type TEXT NOT NULL CHECK(entity_type IN ('instruction','task')),
 entity_id BIGINT NOT NULL,
 title TEXT NOT NULL,
 event_id BIGINT,
 read_at TIMESTAMPTZ,
 opened_at TIMESTAMPTZ,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 UNIQUE(user_id,entity_type,entity_id,kind,event_id)
);
CREATE INDEX IF NOT EXISTS idx_work_notifications_user ON work_notifications(user_id,id DESC);
CREATE OR REPLACE FUNCTION reject_instruction_mutation() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN RAISE EXCEPTION 'Une instruction émise ne peut être modifiée ou supprimée'; END $$;
CREATE TRIGGER instruction_immutable BEFORE UPDATE OR DELETE ON instructions FOR EACH ROW EXECUTE FUNCTION reject_instruction_mutation();
CREATE OR REPLACE FUNCTION reject_work_event_mutation() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN RAISE EXCEPTION 'Un événement de traitement ne peut être modifié ou supprimé'; END $$;
CREATE TRIGGER instruction_event_immutable BEFORE UPDATE OR DELETE ON instruction_events FOR EACH ROW EXECUTE FUNCTION reject_work_event_mutation();
CREATE TRIGGER task_event_immutable BEFORE UPDATE OR DELETE ON task_events FOR EACH ROW EXECUTE FUNCTION reject_work_event_mutation();
